# ----------------------------------------------------------------------------------------------
# 6.  COROLLARY 4:  a monomial can only be e-computable for e <= a_0
#     What is EXECUTED here is a finite census only.  The general statement of Corollary 4 --
#     arbitrary n, arbitrary 0 < a_0 <= ... <= a_n -- is the paper's proof of that corollary
#     (from Corollary 3 plus HF(A_F,j) >= 1 on 0 <= j <= d), IMPORTED here, not run.
# ----------------------------------------------------------------------------------------------
head('Corollary 4 on a FINITE CENSUS: 120 monomials in 2-4 variables with exponents 1..5, '
     'e up to d+2 -- e-computable => e <= a_0 on every censused pair. The general case '
     '(arbitrary n, arbitrary ordered positive exponents) is the paper\'s proof of Corollary 4, '
     'IMPORTED, not executed below')

fam = []
for n in (1, 2, 3):
    for a in product(range(1, 6), repeat=n + 1):
        if not all(a[i] <= a[i + 1] for i in range(n)):
            continue
        fam.append(a)
bad_N, bad_fwd, bad_prop, extra, checked_e, a0_one = [], [], [], [], 0, 0
for a in fam:
    nv, d = len(a), sum(a)
    perp = [tuple((a[i] + 1) if i == k else 0 for i in range(nv)) for k in range(nv)]
    h = hf_mon_quot(perp, nv, d + 1)
    Nf = 1
    for ai in a:
        Nf *= (ai + 1)
    rk = Nf // (a[0] + 1)
    if sum(h) != Nf or h[d] != 1 or any(v == 0 for v in h[:d + 1]):
        bad_N.append(a)
    for e in range(1, d + 3):
        cap = sum(h[:max(d - e + 1, 0)])
        excluded = (e * rk > cap)
        checked_e += 1
        if e > a[0] and not excluded:
            bad_fwd.append((a, e, cap, e * rk))     # would break Corollary 4
        if e <= a[0] and excluded:
            extra.append((a, e, cap, e * rk))       # allowed: the cap may be sharper than e<=a_0
        if 2 * e <= a[0] + 1 and excluded:
            bad_prop.append((a, e, cap, e * rk))    # would CONTRADICT Proposition 4.2
    if a[0] == 1:
        a0_one += 1
check('monomial_family_invariants_N_and_socle_degree',
      not bad_N, '%d monomials in 2..4 variables with exponents in 1..5: sum HF = prod(a_i+1), '
                 'HF(A,d) = 1, HF(A,i) > 0 on 0..d, in every case' % len(fam))
check('corollary4_every_e_above_a0_is_excluded_by_the_cap_on_the_censused_family',
      not bad_fwd, '%d (monomial, e) pairs tested, e up to d+2; e > a_0 implies e*rk > cap '
                   'without exception ON THIS CENSUS (2..4 variables, exponents 1..5). Arbitrary '
                   'n and arbitrary exponents are covered by the paper\'s proof of Corollary 4, '
                   'not by this loop' % checked_e)
check('corollary4_never_contradicts_proposition_4_2_of_the_source',
      not bad_prop, 'the cap is SILENT on every e in the source\'s positive range '
                    '1 <= e <= (a_0+1)/2, for all %d monomials' % len(fam))
check('the_cap_is_sometimes_strictly_sharper_than_e_at_most_a0_and_that_is_recorded_not_hidden',
      len(extra) == 5 and all(len(x[0]) == 2 for x in extra),
      '%d pairs with e <= a_0 are ALSO excluded, all in two variables: %s. Corollary 4 states '
      'only the implication e-computable => e <= a_0, which is what is checked above; it does '
      'not claim the converse, and these five show the converse is false'
      % (len(extra), [(x[0], 'e=%d' % x[1]) for x in extra]))
check('for_a0_equal_1_the_window_closes_to_e_equal_1_exactly', a0_one > 0,
      '%d of the family have a_0 = 1; there Proposition 4.2 gives e = 1 and Corollary 4 '
      'forbids e >= 2, so e-computability holds exactly for e = 1' % a0_one)
