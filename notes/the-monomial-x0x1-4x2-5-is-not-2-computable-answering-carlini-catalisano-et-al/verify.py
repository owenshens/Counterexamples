# ----------------------------------------------------------------------------------------------
# 1.  monomials, monomial ideals, apolarity -- all exact integer arithmetic
# ----------------------------------------------------------------------------------------------
def mons(nv, deg):
    """Every exponent vector of length nv and total degree deg, in a fixed order."""
    if nv == 1:
        yield (deg,)
        return
    for a in range(deg + 1):
        for rest in mons(nv - 1, deg - a):
            yield (a,) + rest


def in_mon_ideal(u, gens):
    """u in the monomial ideal generated by `gens` <=> some generator divides u."""
    return any(all(u[i] >= g[i] for i in range(len(u))) for g in gens)


def apolar_act(m, F):
    """m o F, where the variable X_i of T acts on S as d/dx_i.  F is {exponent: integer}."""
    out = {}
    nv = len(m)
    for e, c in F.items():
        if all(e[i] >= m[i] for i in range(nv)):
            coef = c
            for i in range(nv):
                for k in range(m[i]):
                    coef *= (e[i] - k)
            key = tuple(e[i] - m[i] for i in range(nv))
            out[key] = out.get(key, 0) + coef
    return dict((k, v) for k, v in out.items() if v != 0)


def rank(rows):
    """Exact rank over Q of a list of integer rows, by Fraction Gaussian elimination."""
    M = [[Fraction(x) for x in r] for r in rows]
    if not M:
        return 0
    ncol = len(M[0])
    r = 0
    for c in range(ncol):
        piv = None
        for i in range(r, len(M)):
            if M[i][c] != 0:
                piv = i
                break
        if piv is None:
            continue
        M[r], M[piv] = M[piv], M[r]
        pv = M[r][c]
        for i in range(r + 1, len(M)):
            if M[i][c] != 0:
                f = M[i][c] / pv
                for j in range(c, ncol):
                    M[i][j] -= f * M[r][j]
        r += 1
    return r


def hf_apolar(F, nv, d, jmax):
    """HF(T/F^perp, j) for j = 0..jmax, computed as rank of the apolarity pairing
    T_j -> S_{d-j}, m |-> m o F.  Independent of any printed ideal."""
    out = []
    for j in range(jmax + 1):
        if d - j < 0:
            out.append(0)
            continue
        Sd = list(mons(nv, d - j))
        idx = dict((m, i) for i, m in enumerate(Sd))
        rows = []
        for m in mons(nv, j):
            v = [0] * len(Sd)
            for k, c in apolar_act(m, F).items():
                v[idx[k]] = c
            rows.append(v)
        out.append(rank(rows))
    return out


def hf_mon_quot(gens, nv, jmax):
    """HF(T/J, j) for a MONOMIAL ideal J, by counting standard monomials."""
    return [sum(1 for u in mons(nv, j) if not in_mon_ideal(u, gens)) for j in range(jmax + 1)]


def ideal_deg_dim(gens_poly, nv, j):
    """dim_k of the degree-j piece of the ideal generated by the (possibly non-monomial) forms
    in `gens_poly`, each a dict {exponent: integer} that is homogeneous."""
    basis = list(mons(nv, j))
    idx = dict((m, i) for i, m in enumerate(basis))
    rows = []
    for g in gens_poly:
        dg = sum(next(iter(g)))
        if dg > j:
            continue
        for m in mons(nv, j - dg):
            v = [0] * len(basis)
            for e, c in g.items():
                key = tuple(e[i] + m[i] for i in range(nv))
                v[idx[key]] += c
            rows.append(v)
    return rank(rows)


