head('Lemma 2, step by step, at e = 2 on G_1 (d - e + 1 = 9)')

E = 2
THR = D - E + 1                                      # = 9
check('the_threshold_degree_is_9', THR == 9, 'd - e + 1 = %d - %d + 1 = %d' % (D, E, THR))

# Step 0: everything of degree > d annihilates G_1.
check('step0_every_monomial_of_degree_above_d_annihilates_G1',
      all(apolar_act(m, G1) == {} for j in range(D + 1, JMAX + 1) for m in mons(3, j)),
      'T_{>= %d} is contained in G_1^perp' % (D + 1))

# Step 1: for every monomial h of degree >= 9 and every monomial g of degree 2, h*g in G_1^perp.
#         By bilinearity of (h,g) |-> h*g this gives T_{>=9} * I_e in G_1^perp for EVERY
#         subspace I_e of T_2 whatever, hence T_{>=9} in G_1^perp : I for every I = (I_e).
pairs = 0
step1 = True
for j in range(THR, JMAX + 1):
    for h in mons(3, j):
        for g in mons(3, E):
            pairs += 1
            if apolar_act(tuple(h[i] + g[i] for i in range(3)), G1) != {}:
                step1 = False
check('step1_T_ge_9_times_T_2_lies_in_G1_perp', step1,
      '%d products h*g with deg h >= %d, deg g = %d all annihilate G_1 (deg hg >= %d > d)'
      % (pairs, THR, E, THR + E))

# Step 2: the containment is STRICT over G_1^perp, because HF(A, d-e+1) > 0.
