hf_apo = hf_apolar(G1, 3, D, JMAX)
check('hilbert_function_from_monomial_count_equals_printed_vector',
      hf_mon[:D + 1] == HF_PRINTED, 'HF(A) = %s' % (hf_mon[:D + 1],))
check('hilbert_function_from_apolarity_ranks_agrees_with_monomial_count',
      hf_apo == hf_mon, 'two independent routes agree in every degree 0..%d' % JMAX)
check('hilbert_function_vanishes_above_the_socle_degree',
      all(v == 0 for v in hf_mon[D + 1:]) and hf_mon[D] > 0,
      'HF(A,j) = 0 for j > %d, HF(A,%d) = %d' % (D, D, hf_mon[D]))
check('hilbert_function_is_positive_exactly_on_0_to_d',
      all(hf_mon[j] > 0 for j in range(D + 1)),
      'HF(A,j) > 0 for every 0 <= j <= %d' % D)
check('gorenstein_symmetry_of_the_hilbert_function',
      all(hf_mon[j] == hf_mon[D - j] for j in range(D + 1)),
      'HF(A,j) = HF(A,%d-j) for all j -- A is artinian Gorenstein of socle degree %d' % (D, D))

NG1 = sum(hf_mon)
