def section_D6():
    """(i) the computed Lambda basis is a Z-basis of ker A -- and is the very
    basis that E1/E4 evaluate; (ii) Lemma 6 (character duality), the algebraic
    engine of the converse inclusion, is verified exactly for the paper's own A
    on the N-torsion mu_N of the torus: im phi = ann(ker A) inside mu_N^Omega.
    For d = 3 and d = 4 both sides are enumerated element by element; for
    d = 2..8 the two dimensions are computed over F_N and compared."""
    ok = True
    why = []
    exhaustive = []
    for d in range(2, 9):
        omega = PAPER_OMEGA3 if d == 3 else omega_paper(d)
        rows = A_rows(omega, d)
        mm, piv = rref(rows)
        nc = len(omega)
        free = [c for c in range(nc) if c not in piv]

        # (i) integral with an identity minor on the free columns
        basis = []
        for f in free:
            v = [0] * nc
            v[f] = 1
            good = True
            for r, c in enumerate(piv):
                e = -mm[r][f]
                if e.denominator != 1:
                    ok = False
                    good = False
                    why.append("d=%d: kernel entry %s not integral" % (d, e))
                else:
                    v[c] = int(e)
            if good:
                basis.append(v)
        # the licence must attach to the object E1/E4 actually use
        if [list(b) for b in kernel_basis(rows, nc)] != basis:
            ok = False
            why.append("d=%d: kernel_basis() != identity-minor basis" % d)
        if len(basis) != nc - d:
            ok = False
            why.append("d=%d: %d kernel vectors, want %d"
                       % (d, len(basis), nc - d))

        # (ii) character duality on mu_N, N odd (coprime to every elementary
        # divisor of A, which are 1,2,...,2), by dimension count over F_N.
        # im phi_N = {(<eps,theta>)_eps} = image of A^T, of dimension rank A;
        # ann(Lambda) = null space of the Lambda basis, of dimension nc - rank.
        # im is contained in ann for free ((A m).theta = m.(A^T theta)), so
        # equality is exactly the equality of the two dimensions.
        for N in (5, 7, 11):
            ra = rank_mod(rows, N)
            rl = rank_mod(basis, N) if basis else 0
            if ra != d or rl != nc - d or (nc - rl) != ra:
                ok = False
                why.append("d=%d N=%d: dim im=%d, dim ann=%d"
                           % (d, N, ra, nc - rl))
            for b in basis:
                for k in range(d):
                    if sum(b[j] * int(rows[k][j]) for j in range(nc)) % N:
                        ok = False
                        why.append("d=%d N=%d: im not inside ann" % (d, N))

        # (iii) for the small d, enumerate BOTH sides and compare as sets
        if d in (3, 4):
            N = 7 if d == 3 else 5
            img = set()
            for th in itertools.product(range(N), repeat=d):
                img.add(tuple(sum(e * t for e, t in zip(eps, th)) % N
                              for eps in omega))
            ann = set()
            for u in itertools.product(range(N), repeat=nc):
                if all(sum(b[j] * u[j] for j in range(nc)) % N == 0
                       for b in basis):
                    ann.add(u)
            if img != ann:
                ok = False
                why.append("d=%d N=%d: |im|=%d |ann|=%d, im != ann"
                           % (d, N, len(img), len(ann)))
            exhaustive.append("d=%d,N=%d: |im|=|ann|=%d"
                              % (d, N, len(img)))

    ck("D6_Z_basis_of_Lambda_and_character_duality", ok,
       "the rref kernel basis is integral with an identity minor, equals the "
       "basis E1/E4 evaluate, and has rank 2^(d-1)-d; Lemma 6 holds on mu_N "
       "for N=5,7,11 (dim im = dim ann = d) for d=2..8, and both sides are "
       "enumerated exhaustively for " + "; ".join(exhaustive)
       + ("" if ok else "  FAILURES: " + "; ".join(why[:3])))


