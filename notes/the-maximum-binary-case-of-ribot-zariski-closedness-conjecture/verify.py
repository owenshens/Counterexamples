# 4. the paper's objects, built from scratch
# ----------------------------------------------------------------------

def cube(d):
    """all x in {0,1}^d, lexicographic (x_1 most significant)"""
    return [tuple(t) for t in itertools.product((0, 1), repeat=d)]


def var_index(x):
    """position of the coordinate t_x among the 2^d variables"""
    k = 0
    for b in x:
        k = 2 * k + b
    return k


def E_delta(d, delta):
    return [x for x in cube(d) if sum(x) % 2 == delta]


def hamming(x, y):
    return sum(1 for a, b in zip(x, y) if a != b)


def scaled_p(d, eps):
    """the complex polynomial 2^d * p_eps in the 2^d variables t_x.

    Coefficient of t_x is i^{|x|} * eps^x, straight from the definition."""
    nv = 1 << d
    out = c_zero()
    for x in cube(d):
        sgn = 1
        for k in range(d):
            if x[k] == 1 and eps[k] == -1:
                sgn = -sgn
        coeff = c_scal((p_var(var_index(x), nv), p_zero()), IPOW[sum(x) % 4])
        out = c_add(out, c_scal(coeff, gz(sgn, 0)))
    return out


def omega_paper(d):
    """one representative per antipodal pair: those with eps_1 = +1 ...

    for d = 3 the paper's own list is used verbatim (see PAPER_OMEGA3)."""
    return [tuple(e) for e in itertools.product((1, -1), repeat=d) if e[0] == 1]


