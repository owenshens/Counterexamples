def A_rows(omega, d):
    """the d x |Omega| integer matrix of A(m) = sum m_eps eps"""
    return [[Fraction(eps[k]) for eps in omega] for k in range(d)]


def A_apply(omega, m, d):
    return tuple(sum(m[j] * omega[j][k] for j in range(len(omega)))
                 for k in range(d))


def admissible_omegas(d):
    """every choice of one representative per antipodal pair"""
    reps = [e for e in itertools.product((1, -1), repeat=d) if e[0] == 1]
    for signs in itertools.product((1, -1), repeat=len(reps)):
        yield [tuple(s * c for c in e) for s, e in zip(signs, reps)]


