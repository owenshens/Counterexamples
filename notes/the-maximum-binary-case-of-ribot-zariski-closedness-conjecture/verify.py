def infinitesimal_rot(d, t, k):
    """J_k . T with J = [[0,-1],[1,0]]: the derivative of the mode-k rotation"""
    return rotate_mode(d, t, k, Fraction(0), Fraction(1))


def tangent_vectors(d, t0, angles=None):
    """basis of V_{E_0} plus the d orbit directions, pushed by the rotation"""
    vecs = []
    for x in E_delta(d, 0):
        e = [Fraction(0)] * (1 << d)
        e[var_index(x)] = Fraction(1)
        vecs.append(e)
    for k in range(d):
        vecs.append(infinitesimal_rot(d, t0, k))
    if angles is not None:
        vecs = [rotate_all(d, v, angles) for v in vecs]
    return vecs


def section_G():
    print("--- G. dimension and the local converse ---")
    rng = random.Random(99)

    ok, detail = True, []
    for d in range(2, 9):
        want = (1 << (d - 1)) + d
        for _ in range(3):
            t0 = random_tensor_in_V(d, 0, rng)
            vecs = tangent_vectors(d, t0)
            r = rank(vecs)
            # len(vecs) is exactly 2^(d-1)+d, i.e. the target; augment with a
            # dependent vector so the count and the answer differ.
            r_aug = rank(vecs + [[a + b for a, b in zip(vecs[0], vecs[-1])]])
            if r != want or r_aug != want:
                ok = False
        if d <= 5 or d == 8:
            detail.append("d=%d:%d" % (d, want))
    ck("G1_dim_X_E0_is_2^(d-1)_plus_d", ok,
       "exact tangent rank at generic points equals 2^(d-1)+d for "
       "d=2..8 (" + ", ".join(detail) + ")")

