def rotate_mode(d, t, k, c, s):
    """apply [[c,-s],[s,c]] in mode k to the dict-free list t of length 2^d"""
    n = 1 << d
    out = list(t)
    bit = 1 << (d - 1 - k)
    for v in range(n):
        if v & bit:
            continue
        w = v | bit
        a, b = t[v], t[w]
        out[v] = c * a - s * b
        out[w] = s * a + c * b
    return out


def rotate_all(d, t, angles):
    for k, (c, s) in enumerate(angles):
        t = rotate_mode(d, t, k, c, s)
    return t


def p_eps_value(d, eps, t):
    """p_eps(T) as an exact Gaussian rational, straight from the definition"""
    acc = gz(0, 0)
    for x in cube(d):
        sgn = 1
        for k in range(d):
            if x[k] == 1 and eps[k] == -1:
                sgn = -sgn
        term = gmul(IPOW[sum(x) % 4], gz(t[var_index(x)] * sgn, 0))
        acc = gadd(acc, term)
    inv = Fraction(1, 1 << d)
    return (acc[0] * inv, acc[1] * inv)


def phi_m_value(d, omega, m, t):
    """Phi_m(T) exactly: Im( prod p_eps^{m+} conj(p_eps)^{m-} )"""
    acc = gz(1, 0)
    for j, eps in enumerate(omega):
        p = p_eps_value(d, eps, t)
        if m[j] > 0:
            acc = gmul(acc, gpow(p, m[j]))
        elif m[j] < 0:
            acc = gmul(acc, gpow(gconj(p), -m[j]))
    return acc[1]


def z_pow_eps(angles, eps):
    """z^eps for z_k = c_k + i s_k, exactly"""
    acc = gz(1, 0)
    for (c, s), e in zip(angles, eps):
        z = (c, s)
        acc = gmul(acc, z if e == 1 else gconj(z))
    return acc


def random_tensor_in_V(d, delta, rng):
    """a rational tensor supported on E_delta"""
    t = [Fraction(0)] * (1 << d)
    for x in E_delta(d, delta):
        t[var_index(x)] = Fraction(rng.randint(-9, 9), rng.randint(1, 5))
    return t


def random_tensor(d, rng):
    return [Fraction(rng.randint(-9, 9), rng.randint(1, 5))
            for _ in range(1 << d)]


