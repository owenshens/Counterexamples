# 6. the hypercube graph Q_d: matching, independence number, census
# ----------------------------------------------------------------------

def qd_adj(d):
    """neighbour bitmask per vertex of Q_d, vertices 0..2^d-1"""
    n = 1 << d
    return [sum(1 << (v ^ (1 << k)) for k in range(d)) for v in range(n)]


def max_matching_qd(d):
    """maximum bipartite matching of Q_d by augmenting paths (Kuhn)"""
    n = 1 << d
    left = [v for v in range(n) if bin(v).count("1") % 2 == 0]
    nb = [[v ^ (1 << k) for k in range(d)] for v in range(n)]
    match = {}

    def try_aug(u, seen):
        for w in nb[u]:
            if w in seen:
                continue
            seen.add(w)
            if w not in match or try_aug(match[w], seen):
                match[w] = u
                return True
        return False

    size = 0
    for u in left:
        if try_aug(u, set()):
            size += 1
    return size, match


def census_max_independent(d, target, node_cap=None):
    """all independent sets of Q_d of size exactly `target`, exhaustively.

    Returns (list_of_sets, nodes_explored, complete_flag)."""
    n = 1 << d
    adj = qd_adj(d)
    found = []
    nodes = [0]
    truncated = [False]

    def dfs(i, chosen, banned, cnt):
        nodes[0] += 1
        if node_cap is not None and nodes[0] > node_cap:
            truncated[0] = True
            return
        if cnt == target:
            found.append(tuple(chosen))
            return
        if cnt + (n - i) < target:
            return
        if i >= n:
            return
        if not (banned >> i) & 1:
            chosen.append(i)
            dfs(i + 1, chosen, banned | adj[i], cnt + 1)
            chosen.pop()
        dfs(i + 1, chosen, banned, cnt)

    dfs(0, [], 0, 0)
    return found, nodes[0], not truncated[0]


def brute_alpha(d):
    """independence number of Q_d by exhaustive subset search (small d)"""
    n = 1 << d
    adj = qd_adj(d)
    best = 0
    for mask in range(1 << n):
        ok = True
        m = mask
        while m:
            v = (m & -m).bit_length() - 1
            if adj[v] & mask:
                ok = False
                break
            m &= m - 1
        if ok:
            c = bin(mask).count("1")
            if c > best:
                best = c
    return best


