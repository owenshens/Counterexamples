CHECKS = []


def ck(name, ok, detail=""):
    CHECKS.append((name, bool(ok)))
    tag = "PASS" if ok else "FAIL"
    if detail:
        print("%s %s [%s]" % (tag, name, detail))
    else:
        print("%s %s" % (tag, name))
    return bool(ok)


def finish():
    n = len(CHECKS)
    bad = [c for c in CHECKS if not c[1]]
    if not bad:
        print("VERDICT: ALL %d CHECKS PASS" % n)
        sys.exit(0)
    print("VERDICT: %d OF %d CHECKS FAILED" % (len(bad), n))
    sys.exit(1)


# ----------------------------------------------------------------------
# 1. exact Gaussian rationals, as pairs (re, im) of Fractions
# ----------------------------------------------------------------------

def gz(re=0, im=0):
    return (Fraction(re), Fraction(im))


def gadd(a, b):
    return (a[0] + b[0], a[1] + b[1])


def gsub(a, b):
    return (a[0] - b[0], a[1] - b[1])


def gmul(a, b):
    return (a[0] * b[0] - a[1] * b[1], a[0] * b[1] + a[1] * b[0])


def gconj(a):
    return (a[0], -a[1])


def gpow(a, n):
    r = gz(1, 0)
    for _ in range(n):
        r = gmul(r, a)
    return r


def gis_zero(a):
    return a[0] == 0 and a[1] == 0


# i^k, exactly
IPOW = [gz(1, 0), gz(0, 1), gz(-1, 0), gz(0, -1)]


# ----------------------------------------------------------------------
# 2. exact multivariate polynomials: dict {exponent tuple -> Fraction}
# ----------------------------------------------------------------------

def p_zero():
    return {}


def p_const(c, nv):
    c = Fraction(c)
    return {} if c == 0 else {(0,) * nv: c}


def p_var(k, nv):
    e = [0] * nv
    e[k] = 1
    return {tuple(e): Fraction(1)}


def p_add(a, b):
    r = dict(a)
    for e, c in b.items():
        v = r.get(e, Fraction(0)) + c
        if v == 0:
            r.pop(e, None)
        else:
            r[e] = v
    return r


def p_scal(a, c):
    c = Fraction(c)
    if c == 0:
        return {}
    return dict((e, v * c) for e, v in a.items())


def p_sub(a, b):
    return p_add(a, p_scal(b, -1))


def p_mul(a, b):
    r = {}
    for ea, ca in a.items():
        for eb, cb in b.items():
            e = tuple(x + y for x, y in zip(ea, eb))
            v = r.get(e, Fraction(0)) + ca * cb
            if v == 0:
                r.pop(e, None)
            else:
                r[e] = v
    return r


def p_eq(a, b):
    return p_sub(a, b) == {}


def p_degrees(a):
    return set(sum(e) for e in a)


def p_eval(a, vals):
    tot = Fraction(0)
    for e, c in a.items():
        t = c
        for k, ek in enumerate(e):
            if ek:
                t *= vals[k] ** ek
        tot += t
    return tot


def p_diff(a, k):
    r = {}
    for e, c in a.items():
        if e[k] == 0:
            continue
        f = list(e)
        f[k] -= 1
        f = tuple(f)
        v = r.get(f, Fraction(0)) + c * e[k]
        if v == 0:
            r.pop(f, None)
        else:
            r[f] = v
    return r


# ----------------------------------------------------------------------
# 3. complex polynomials: pair (real part, imaginary part)
# ----------------------------------------------------------------------

def c_zero():
    return (p_zero(), p_zero())


def c_add(a, b):
    return (p_add(a[0], b[0]), p_add(a[1], b[1]))


def c_mul(a, b):
    return (p_sub(p_mul(a[0], b[0]), p_mul(a[1], b[1])),
            p_add(p_mul(a[0], b[1]), p_mul(a[1], b[0])))


def c_conj(a):
    return (a[0], p_scal(a[1], -1))


def c_scal(a, g):
    """multiply by the Gaussian rational g = (gr, gi)"""
    gr, gi = g
    return (p_sub(p_scal(a[0], gr), p_scal(a[1], gi)),
            p_add(p_scal(a[0], gi), p_scal(a[1], gr)))


def c_pow(a, n, nv):
    r = (p_const(1, nv), p_zero())
    for _ in range(n):
        r = c_mul(r, a)
    return r


