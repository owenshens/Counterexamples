# 5. exact linear algebra over Q
# ----------------------------------------------------------------------

def rref(rows):
    """reduced row echelon form; returns (matrix, pivot columns)"""
    m = [[Fraction(v) for v in r] for r in rows]
    if not m:
        return [], []
    ncol = len(m[0])
    piv = []
    r = 0
    for c in range(ncol):
        s = None
        for k in range(r, len(m)):
            if m[k][c] != 0:
                s = k
                break
        if s is None:
            continue
        m[r], m[s] = m[s], m[r]
        inv = Fraction(1) / m[r][c]
        m[r] = [v * inv for v in m[r]]
        for k in range(len(m)):
            if k != r and m[k][c] != 0:
                f = m[k][c]
                m[k] = [a - f * b for a, b in zip(m[k], m[r])]
        piv.append(c)
        r += 1
        if r == len(m):
            break
    return m, piv


def rank(rows):
    return len(rref(rows)[1])


def kernel_basis(rows, ncol):
    """basis of {v : rows . v = 0}, entries cleared to integers"""
    m, piv = rref(rows)
    free = [c for c in range(ncol) if c not in piv]
    out = []
    for f in free:
        v = [Fraction(0)] * ncol
        v[f] = Fraction(1)
        for r, c in enumerate(piv):
            v[c] = -m[r][f]
        den = 1
        for a in v:
            den = den * a.denominator // gcd(den, a.denominator)
        iv = [int(a * den) for a in v]
        g = 0
        for a in iv:
            g = gcd(g, abs(a))
        if g > 1:
            iv = [a // g for a in iv]
        out.append(iv)
    return out


def gcd(a, b):
    while b:
        a, b = b, a % b
    return abs(a)


def rank_mod(rows, p):
    """rank over the prime field F_p, exact integer arithmetic"""
    m = [[int(v) % p for v in r] for r in rows]
    if not m:
        return 0
    ncol = len(m[0])
    r = 0
    for c in range(ncol):
        s = None
        for k in range(r, len(m)):
            if m[k][c] % p:
                s = k
                break
        if s is None:
            continue
        m[r], m[s] = m[s], m[r]
        inv = pow(m[r][c], p - 2, p)
        m[r] = [(v * inv) % p for v in m[r]]
        for k in range(len(m)):
            if k != r and m[k][c] % p:
                f = m[k][c]
                m[k] = [(a - f * b) % p for a, b in zip(m[k], m[r])]
        r += 1
        if r == len(m):
            break
    return r


