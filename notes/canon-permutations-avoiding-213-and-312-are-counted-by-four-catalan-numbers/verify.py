# 4.  THE TRANSFER-MATRIX LADDER (the characterisation is nowhere used)
# ---------------------------------------------------------------------------
def ladder_count(k, sig, pats):
    """Count the canon words of C_3^k with witness sig that avoid every literal pattern
    in pats, by dynamic programming over prefixes.  The state is
    (c_1, c_2, c_3; greedy match length of each pattern), where c_i counts the letters
    sig[i] emitted so far.  The canon condition enters only as the prefix inequality
    c_1 >= c_2 >= c_3 and avoidance only through the greedy matcher: neither 4C_k nor
    the normal forms of Theorem 1 appear."""
    role = dict((sig[i], i) for i in range(3))
    cur = {(0, 0, 0) + tuple(0 for _ in pats): 1}
    for _ in range(3 * k):
        nxt = defaultdict(int)
        for st, cnt in cur.items():
            c = st[:3]
            m = st[3:]
            for v in (1, 2, 3):
                i = role[v]
                if c[i] >= k:
                    continue
                if i > 0 and c[i - 1] <= c[i]:
                    continue
                dead = False
                nm = []
                for t in range(len(pats)):
                    j = m[t]
                    if j < 3 and pats[t][j] == v:
                        j += 1
                    if j == 3:
                        dead = True
                        break
                    nm.append(j)
                if dead:
                    continue
                nc = list(c)
                nc[i] += 1
                nxt[(nc[0], nc[1], nc[2]) + tuple(nm)] += cnt
        cur = nxt
    return sum(cnt for st, cnt in cur.items()
               if st[0] == k and st[1] == k and st[2] == k)


def ballot_words(k):
    """All words on k 2's and k 3's in which the j-th 2 precedes the j-th 3 for every
    j, enumerated straight from that condition."""
    out = []
    pref = []

    def rec(a, b):
        if a == k and b == k:
            out.append(tuple(pref))
            return
        if a < k:
            pref.append(2)
            rec(a + 1, b)
            pref.pop()
        if b < a:
            pref.append(3)
            rec(a, b + 1)
            pref.pop()
    rec(0, 0)
    return out


