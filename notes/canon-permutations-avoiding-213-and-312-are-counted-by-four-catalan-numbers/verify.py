# 2.  THE TWO NOTIONS OF PATTERN CONTAINMENT
# ---------------------------------------------------------------------------
def contains_order(w, p):
    """THE DEFINITION, verbatim: w contains the pattern p when some length-3
    subsequence of w has the same relative order as p.  For p a permutation of (1,2,3)
    the three entries of an occurrence are pairwise distinct.  No literalisation is
    assumed anywhere in this routine."""
    n = len(w)
    for i in range(n):
        for j in range(i + 1, n):
            for l in range(j + 1, n):
                a, b, c = w[i], w[j], w[l]
                if len({a, b, c}) != 3:
                    continue
                if ((a < b) == (p[0] < p[1]) and (a < c) == (p[0] < p[2])
                        and (b < c) == (p[1] < p[2])):
                    return True
    return False


def contains_literal_brute(w, p):
    """Is (p[0], p[1], p[2]) a literal subsequence of w?  Brute force over triples."""
    n = len(w)
    for i in range(n):
        if w[i] != p[0]:
            continue
        for j in range(i + 1, n):
            if w[j] != p[1]:
                continue
            for l in range(j + 1, n):
                if w[l] == p[2]:
                    return True
    return False


def contains_literal(w, p):
    """The same question answered by one greedy left-to-right scan.  Used for the large
    enumerations; its agreement with contains_literal_brute is itself a check below."""
    idx = 0
    for x in w:
        if x == p[idx]:
            idx += 1
            if idx == 3:
                return True
    return False


def avoids_all(w, pats, decider):
    return not any(decider(w, p) for p in pats)


