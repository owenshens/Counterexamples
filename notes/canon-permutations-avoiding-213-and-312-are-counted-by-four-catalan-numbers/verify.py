# 3.  CANON PERMUTATIONS: THE DEFINITION, AND THE TABLEAU PARAMETERISATION
# ---------------------------------------------------------------------------
def multiset_words(n, k):
    """All (nk)!/(k!)^n arrangements of the multiset {1^k, ..., n^k}."""
    counts = [0] * n
    pref = []

    def rec():
        if len(pref) == n * k:
            yield tuple(pref)
            return
        for x in range(1, n + 1):
            if counts[x - 1] < k:
                counts[x - 1] += 1
                pref.append(x)
                for y in rec():
                    yield y
                pref.pop()
                counts[x - 1] -= 1
    return rec()


def canon_witness_by_definition(w, n, k):
    """THE DEFINITION: w is canon with witness sigma iff for every j in [k] the
    subsequence of j-th copies, read left to right, spells sigma.  Returns sigma, or
    None if w is not canon.  Knows nothing about tableaux."""
    occ = dict((x, []) for x in range(1, n + 1))
    for i, x in enumerate(w):
        occ[x].append(i)
    sig = None
    for j in range(k):
        layer = tuple(x for _, x in sorted((occ[x][j], x) for x in range(1, n + 1)))
        if sig is None:
            sig = layer
        elif layer != sig:
            return None
    return sig


def canon_witness_by_prefix_rule(w, n, k):
    """The same question by the LATTICE-WORD rule: let sigma be the order in which the
    letters first occur; w is canon with witness sigma iff in every prefix the count of
    sigma_1's is >= that of sigma_2's is >= ... .  Returns sigma or None."""
    firsts = []
    for x in w:
        if x not in firsts:
            firsts.append(x)
    if len(firsts) != n:
        return None
    sig = tuple(firsts)
    role = dict((sig[i], i) for i in range(n))
    c = [0] * n
    for x in w:
        c[role[x]] += 1
        for i in range(1, n):
            if c[i] > c[i - 1]:
                return None
    return sig


def syt_rect(rows, k):
    """Generator over standard Young tableaux of shape (k^rows): fillings of a
    rows x k rectangle by 1..rows*k increasing along rows and down columns."""
    R = [[] for _ in range(rows)]

    def rec(m):
        if m > rows * k:
            yield tuple(tuple(r) for r in R)
            return
        for i in range(rows):
            if len(R[i]) < k and (i == 0 or len(R[i - 1]) > len(R[i])):
                R[i].append(m)
                for y in rec(m + 1):
                    yield y
                R[i].pop()
    return rec(1)


def hook_rect(rows, k):
    """The hook-length count of SYT of shape (k^rows), from the hook formula itself; no
    closed form for the three-row case is assumed."""
    N = rows * k
    prod = 1
    for i in range(rows):
        for j in range(k):
            prod *= (rows - 1 - i) + (k - 1 - j) + 1
    return factorial(N) // prod


def word_of(sig, T, k):
    """The canon word whose letter-sigma_i positions are exactly row i of T."""
    w = [0] * (len(sig) * k)
    for i in range(len(sig)):
        for p in T[i]:
            w[p - 1] = sig[i]
    return tuple(w)


