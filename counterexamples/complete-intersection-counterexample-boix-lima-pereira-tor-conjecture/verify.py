# Values transcribed from the paper's statements (targets, never recomputed
# from themselves: each is compared against an independent computation).
CLAIM_COLENGTH = 8
CLAIM_TOR = (8, 22, 22, 8)
CLAIM_TOR1_HS = {3: 8, 4: 14}
CLAIM_HF_I_PLUS_J = [1, 4, 3, 0, 0]
K_LEN = 3          # length of the regular sequence generating I
N_DIM = 4          # dimension of the regular local ring


def grevlex_key(e):
    """Sort key realising graded reverse lex with x > y > z > w.

    Larger key = larger monomial: first by total degree, then by the rightmost
    differing exponent being *smaller* (that is grevlex)."""
    return (sum(e), tuple(-v for v in reversed(e)))


def leading_monomial(p):
    return max(p, key=grevlex_key)


def divides(a, b):
    return all(a[i] <= b[i] for i in range(NVARS))


def binom(n, k):
    if k < 0 or k > n:
        return 0
    r = 1
    for i in range(k):
        r = r * (n - i) // (i + 1)
    return r


def ci_hilbert_function(degrees, nvars, dmax):
    """HF of S/(regular sequence of the given degrees), from the Koszul
    numerator (1-t^d1)...(1-t^dk) divided by (1-t)^nvars, as exact integers."""
    num = [1] + [0] * dmax
    for d in degrees:
        new = list(num)
        for i in range(dmax + 1 - d):
            new[i + d] -= num[i]
        num = new
    for _ in range(nvars):
        acc = 0
        out = []
        for i in range(dmax + 1):
            acc += num[i]
            out.append(acc)
        num = out
    return num


def check_transcription(DMAX):
    ok = len(GENS_I) == K_LEN and len(GENS_J) == N_DIM
    for g in GENS_I + GENS_J:
        ok = ok and len(g) == 2
        ok = ok and all(sum(e) == 2 for e in g)
        ok = ok and all(c == 1 for c in g.values())
    ck("transcription.generators_are_quadratic_binomials", ok,
       "%d + %d homogeneous quadrics, unit coefficients"
       % (len(GENS_I), len(GENS_J)))
    # A product of nonzero polynomials in the domain Q[x,y,z,w] is never zero,
    # so "the products are nonzero" is unfalsifiable and proves nothing.  What
    # is genuinely at stake is that the two ideals are in general position:
    # no generator of either lies in the other, so I+J is strictly bigger than
    # both and I cap J is strictly bigger than I*J (else Tor_1 would vanish).
    QI = Quotient(GENS_I, DMAX)
    QJ = Quotient(GENS_J, DMAX)
    i_in_j = [k for k, f in enumerate(GENS_I)
              if all(v == 0 for v in QJ.class_of(f))]
    j_in_i = [k for k, f in enumerate(GENS_J)
              if all(v == 0 for v in QI.class_of(f))]
    ck("transcription.neither_ideal_contains_a_generator_of_the_other",
       not i_in_j and not j_in_i,
       "generators of I_S inside J_S: %s; of J_S inside I_S: %s"
       % (i_in_j or "none", j_in_i or "none"))


def check_regular_sequences(DMAX):
    hf_i = hilbert_function(GENS_I, DMAX)
    pred_i = ci_hilbert_function([2] * K_LEN, NVARS, DMAX)
    ck("I.hilbert_function_is_that_of_a_complete_intersection",
       hf_i == pred_i,
       "HF(S/I_S)=%s vs Koszul prediction %s" % (hf_i[:6], pred_i[:6]))
    # dim S/I_S = 1 (constant HF 8 = 2^3), so height I_S = 3 = #generators;
    # in the Cohen-Macaulay ring S this forces a regular sequence.
    tail = set(hf_i[K_LEN:])
    ck("I.has_height_three_so_generators_form_a_regular_sequence",
       tail == set([2 ** K_LEN]),
       "HF constant %s in degrees %d..%d" % (sorted(tail), K_LEN, DMAX))

    hf_j = hilbert_function(GENS_J, DMAX)
    pred_j = ci_hilbert_function([2] * N_DIM, NVARS, DMAX)
    ck("J.hilbert_function_is_that_of_a_complete_intersection",
       hf_j == pred_j and sum(hf_j) == 2 ** N_DIM,
       "HF(S/J_S)=%s, length %d" % (hf_j[:6], sum(hf_j)))
    # J_S artinian: once HF vanishes in degree d it vanishes forever, since
    # S_1*(S_d) = S_{d+1}; so m^d is contained in J_S and sqrt(J_S) = m.
    zero_from = None
    for d, v in enumerate(hf_j):
        if v == 0:
            zero_from = d
            break
    ck("J.is_m_primary_radical_is_the_maximal_ideal",
       zero_from is not None and all(v == 0 for v in hf_j[zero_from:]),
       "m^%s contained in J_S" % zero_from)
    return hf_i, hf_j


def check_colength(DMAX):
    gens = GENS_I + GENS_J
    hf = hilbert_function(gens, DMAX)
    ck("sum.hilbert_function_of_S_mod_I_plus_J",
       hf[:len(CLAIM_HF_I_PLUS_J)] == CLAIM_HF_I_PLUS_J
       and all(v == 0 for v in hf[len(CLAIM_HF_I_PLUS_J):]),
       "HF=%s" % hf)
    colen = sum(hf)
    ck("sum.colength_equals_eight", colen == CLAIM_COLENGTH,
       "length(S/(I_S+J_S)) = %d" % colen)

    Q = Quotient(gens, DMAX)
    inside = [i for i, g in enumerate(PAPER_GB)
              if all(v == 0 for v in Q.class_of(g))]
    ck("grobner.listed_basis_elements_lie_in_the_ideal",
       len(inside) == len(PAPER_GB),
       "%d of %d reduce to zero modulo I_S+J_S"
       % (len(inside), len(PAPER_GB)))

    # Membership alone only shows (PAPER_GB) is contained in I_S+J_S.  For the
    # list to be a Grobner *basis* of I_S+J_S it must also generate it.
    # Equal graded dimensions are conclusive only TOGETHER with the containment
    # check above: containment plus equal dimension in every degree gives
    # equality of the two ideals.  On its own this check is passable by an
    # unrelated ideal of the same Hilbert function, so both must hold.
    same = [d for d in range(DMAX + 1)
            if ideal_dim(PAPER_GB, d) == ideal_dim(gens, d)]
    ck("grobner.listed_basis_generates_the_whole_ideal",
       len(same) == DMAX + 1,
       "dim (PAPER_GB)_d = dim (I_S+J_S)_d in degrees %s" % same)

    rows = [Q.class_of({t: Fraction(1)}) for t in PAPER_STD]
    r = rank(rows, Q.dim)
    ck("grobner.standard_monomials_are_a_basis_of_the_quotient",
       r == len(PAPER_STD) and r == colen,
       "%d listed monomials, rank %d, colength %d"
       % (len(PAPER_STD), r, colen))

    # Macaulay's basis criterion: PAPER_GB lies in the ideal, generates it, and
    # the monomials outside the ideal spanned by its grevlex leading terms are
    # exactly the listed standard monomials -- and there are colength-many of
    # them.  That certifies the paper's Grobner claim, not just membership.
    lms = [leading_monomial(p) for p in PAPER_GB]
    std, empty_from = [], None
    for d in range(DMAX + 1):
        here = [m for m in monomials(d)
                if not any(divides(l, m) for l in lms)]
        std.extend(here)
        if not here and empty_from is None:
            empty_from = d
    # The complement of a monomial ideal is closed under division, so once a
    # whole degree is absent no higher degree can contribute.
    ck("grobner.grevlex_leading_terms_cut_out_exactly_the_listed_standard_monomials",
       sorted(std) == sorted(PAPER_STD) and len(std) == colen
       and empty_from is not None,
       "%d standard monomials, first empty degree %s, colength %d"
       % (len(std), empty_from, colen))
    return colen


def tor_lengths(gens_reg, gens_other, DMAX):
    """Lengths of Tor_i(S/(gens_reg), S/(gens_other)) for i = 0..3, as the
    homology of the Koszul complex on gens_reg tensored with the quotient."""
    Q = Quotient(gens_other, DMAX)
    shift = max(pdeg(f) for f in gens_reg)
    topdeg = max([d for d in range(DMAX + 1) if Q.basis_by_deg[d]] + [-1])
    if topdeg < 0 or topdeg + shift > DMAX:
        raise ValueError("second quotient is not known to have finite length "
                         "(top nonzero degree %d of %d); Koszul route needs "
                         "room for multiplication by degree %d"
                         % (topdeg, DMAX, shift))
    mats = [Q.mult_matrix(f) for f in gens_reg]
    d1, d2, d3 = koszul_matrices(Q, mats)
    n = Q.dim
    r1 = rank(d1, n)
    r2 = rank(d2, 3 * n)
    r3 = rank(d3, 3 * n)
    homology = [n - r1, (3 * n - r1) - r2, (3 * n - r2) - r3, n - r3]
    return homology, (d1, d2, d3), Q


def check_tor(colen):
    tor, (d1, d2, d3), Q = tor_lengths(GENS_I, GENS_J, 6)
    n = Q.dim
    z1 = compose(d2, d1, n)
    z2 = compose(d3, d2, 3 * n)
    ck("koszul.tensored_complex_composes_to_zero",
       all(v == 0 for r in z1 for v in r)
       and all(v == 0 for r in z2 for v in r),
       "d1 d2 = 0 and d2 d3 = 0 over the %d-dimensional quotient" % n)
    ck("tor.length_vector_is_8_22_22_8", tuple(tor) == CLAIM_TOR,
       "computed %s" % (tuple(tor),))
    ck("tor.degree_zero_term_matches_the_colength",
       tor[0] == colen,
       "H_0 = %d, length(S/(I_S+J_S)) = %d" % (tor[0], colen))
    ck("tor.vector_is_symmetric_under_koszul_duality",
       all(tor[i] == tor[K_LEN - i] for i in range(K_LEN + 1)),
       "%s reversed is %s" % (tor, tor[::-1]))
    return tor


def check_tor1_hilbert_series(tor, DMAX):
    """HS of (I_S cap J_S)/(I_S J_S) = Tor_1, degree by degree.

    dim (I cap J)_d = dim I_d + dim J_d - dim (I+J)_d, all exact ranks."""
    prod = [pmul(f, g) for f in GENS_I for g in GENS_J]
    hs = {}
    for d in range(DMAX + 1):
        cap = (ideal_dim(GENS_I, d) + ideal_dim(GENS_J, d)
               - ideal_dim(GENS_I + GENS_J, d))
        val = cap - ideal_dim(prod, d)
        if val:
            hs[d] = val
    ck("tor1.hilbert_series_is_8t3_plus_14t4", hs == CLAIM_TOR1_HS,
       "computed %s over degrees 0..%d"
       % (sorted(hs.items()), DMAX))
    ck("tor1.two_independent_computations_agree",
       sum(hs.values()) == tor[1] == CLAIM_TOR[1],
       "intersection route %d, Koszul route %d"
       % (sum(hs.values()), tor[1]))
    return hs


def check_consequences(tor, colen, higher_tor_vanishes):
    predicted = [binom(K_LEN, i) * colen for i in range(K_LEN + 1)]
    strict = [i for i in range(K_LEN + 1) if tor[i] < predicted[i]]
    # The same strict inequality settles two of the paper's three claims: it
    # contradicts the equality of Conjecture 4.2 and, a fortiori, the
    # degreewise LOWER bound asked for in Question 5.1 (whose hypothesis is
    # weaker -- the ideals need only CONTAIN regular sequences of lengths k
    # and n -- so an example generated by regular sequences is an instance).
    ck("consequence.conjecture_4_2_and_question_5_1_lower_bound_fail",
       len(strict) > 0
       and all(tor[i] == predicted[i] for i in range(K_LEN + 1)
               if i not in strict),
       "Tor=%s, conjectured %s, strictly smaller at i=%s -- refutes the "
       "equality of Conjecture 4.2 and the lower bound of Question 5.1"
       % (tor, predicted, strict))
    # Question 5.4's sum runs over i = 0..n, not 0..k.  Summing only the first
    # k+1 terms would UNDERCOUNT the left side and so make the bound easier to
    # violate; the omitted terms i = k+1..n are legitimately dropped only
    # because stage.higher_tor_vanishing certified that they are zero, so that
    # certificate is a conjunct here rather than an assumption elsewhere.
    total = sum(tor)
    bound = (2 ** K_LEN) * colen
    ck("consequence.total_length_bound_of_question_5_4_fails",
       total < bound and higher_tor_vanishes is True,
       "sum_{i=0}^{%d} Tor = %d (terms i=%d..%d contribute 0; vanishing "
       "certified: %s) < %d = 2^%d * %d"
       % (N_DIM, total, K_LEN + 1, N_DIM, higher_tor_vanishes, bound,
          K_LEN, colen))


def check_higher_tor_vanishes(DMAX):
    """Tor_i = 0 for i >= 4.

    The Koszul complex on the four generators of J_S resolves S/J_S, so
    Tor_i = 0 for i >= 5 outright, and Tor_4 = (0 :_B J) where B = S/I_S.
    It therefore suffices to exhibit one element of J_S acting injectively
    on B.

    Injectivity is certified two ways.  The complete one is finite: S/I_S is a
    complete intersection, hence Cohen-Macaulay of dimension 1 and unmixed, so
    g is a nonzerodivisor on B exactly when g avoids every minimal prime of
    I_S, i.e. exactly when S/(I_S + (g)) is artinian.  That is decided by a
    Hilbert function reaching zero, in finitely many degrees, with no
    extrapolation.  The graded-injectivity scan is kept as a cross-check, but
    it alone only inspects degrees 0..DMAX-deg(g) and so cannot conclude by
    itself."""
    B = Quotient(GENS_I, DMAX)

    def nonzerodivisor(g):
        """Complete test: S/(I_S+(g)) artinian <=> g is a nzd on S/I_S."""
        hf = hilbert_function(GENS_I + [g], DMAX)
        for d, v in enumerate(hf):
            if v == 0:
                # HF of a graded quotient, once zero, stays zero, since
                # S_1 * S_d spans S_{d+1}.
                return d if all(u == 0 for u in hf[d:]) else None
        return None

    def injective(g):
        degrees = []
        for d in range(DMAX + 1 - pdeg(g)):
            src = B.basis_by_deg[d]
            if not src:
                continue
            rows = [B.class_of(pmul(g, {monomials(d)[c]: Fraction(1)}))
                    for c in src]
            if rank(rows, B.dim) != len(src):
                return None
            degrees.append(d)
        return degrees

    # Each single generator of J_S is a zerodivisor on B (every one of them
    # factors), so search a short deterministic list of elements of J_S.
    candidates = [("g%d" % (i + 1), g) for i, g in enumerate(GENS_J)]
    total = {}
    for g in GENS_J:
        for e, c in g.items():
            total[e] = total.get(e, Fraction(0)) + c
    candidates.append(("g1+g2+g3+g4", {e: c for e, c in total.items() if c}))
    for k in range(len(GENS_J)):
        mix = {}
        for i, g in enumerate(GENS_J):
            w = Fraction(1 + ((i + k) % 3))
            for e, c in g.items():
                mix[e] = mix.get(e, Fraction(0)) + w * c
        candidates.append(("mix%d" % k, {e: c for e, c in mix.items() if c}))

    found = None
    for label, g in candidates:
        nzd = nonzerodivisor(g)
        if nzd is None:
            continue
        degs = injective(g)
        # The two independent certificates must not disagree.  Distinguish the
        # two ways the scan can fail to corroborate: a kernel was found
        # (degs is None) versus no degree was inspected at all (degs == []).
        # Collapsing them would report a kernel that was never seen.
        if degs is None:
            ck("tor.injectivity_certificates_agree", False,
               "%s is a nonzerodivisor by the artinian test but the graded "
               "scan found a kernel" % label)
            return False
        if not degs:
            ck("tor.injectivity_certificates_agree", False,
               "%s passed the artinian test but the graded scan inspected no "
               "degree at all, so it corroborates nothing" % label)
            return False
        found = (label, nzd, degs)
        break
    vanishes = ck("tor.vanishes_in_degrees_above_three", found is not None,
       ("element %s of J_S is a nonzerodivisor on S/I_S: S/(I_S+(%s)) is "
        "artinian from degree %d, and the graded scan is injective in degrees "
        "%s; hence (0 : J) = 0"
        % (found[0], found[0], found[1], found[2])) if found
       else "no candidate element of J_S was a nonzerodivisor on S/I_S")

    # Two observations, printed rather than asserted: neither is falsifiable as
    # a standalone predicate, so making them "checks" would pad the count.
    singles = [i + 1 for i, g in enumerate(GENS_J)
               if nonzerodivisor(g) is not None]
    print("NOTE: generators of J_S that are already nonzerodivisors on S/I_S: "
          "%s -- so searching past single generators is necessary."
          % (singles or "none"))
    print("NOTE: independently, I_S is generated by a regular sequence of "
          "length %d (certified by the Koszul Hilbert function check above), "
          "so pd(S/I_S) = %d and Tor_i(S/I_S, -) vanishes for i >= %d against "
          "any module; that is the paper's own reason for the vanishing."
          % (K_LEN, K_LEN, K_LEN + 1))
    return vanishes


def check_positive_control():
    """The same machinery on monomial complete intersections where the
    conjectured equality does hold, so a systematic undercount would show."""
    one = Fraction(1)
    ctrl_I = [{mono(x=2): one}, {mono(y=2): one}, {mono(z=2): one}]
    ctrl_J = [{mono(x=3): one}, {mono(y=3): one}, {mono(z=3): one},
              {mono(w=1): one}]
    tor, _, _ = tor_lengths(ctrl_I, ctrl_J, 8)
    colen = sum(hilbert_function(ctrl_I + ctrl_J, 8))
    predicted = [binom(K_LEN, i) * colen for i in range(K_LEN + 1)]
    ck("control.machinery_reproduces_the_conjectured_vector_on_a_monomial_case",
       tor == predicted and colen == 8,
       "control colength %d, Tor %s = %s" % (colen, tor, predicted))


def guarded(label, fn, *args):
    """Run a stage; a stage that cannot even complete is reported as a
    failed check rather than as a traceback."""
    try:
        return fn(*args)
    except Exception as exc:
        ck(label, False, "stage aborted: %s" % exc)
        return None


