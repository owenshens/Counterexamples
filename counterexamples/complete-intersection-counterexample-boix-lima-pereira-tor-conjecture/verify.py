def mono(x=0, y=0, z=0, w=0):
    return (x, y, z, w)


def poly(*terms):
    p = {}
    for coeff, ex in terms:
        p[ex] = p.get(ex, Fraction(0)) + Fraction(coeff)
    return {e: c for e, c in p.items() if c != 0}


