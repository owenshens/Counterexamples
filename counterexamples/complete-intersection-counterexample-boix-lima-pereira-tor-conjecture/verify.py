CHECKS = []


def ck(name, ok, detail=""):
    CHECKS.append((name, bool(ok)))
    tag = "PASS" if ok else "FAIL"
    if detail:
        print("%s %s [%s]" % (tag, name, detail))
    else:
        print("%s %s" % (tag, name))
    return bool(ok)


# ---- graded linear algebra over Q -----------------------------------------

_MONS = {}


def monomials(d):
    """All monomials of S of total degree d, in a fixed deterministic order."""
    if d < 0:
        return []
    if d in _MONS:
        return _MONS[d]
    out = []
    for a in range(d, -1, -1):
        for b in range(d - a, -1, -1):
            for c in range(d - a - b, -1, -1):
                out.append((a, b, c, d - a - b - c))
    _MONS[d] = out
    return out


def mindex(d):
    return {m: i for i, m in enumerate(monomials(d))}


def pmul(p, q):
    r = {}
    for e1, c1 in p.items():
        for e2, c2 in q.items():
            e = (e1[0] + e2[0], e1[1] + e2[1], e1[2] + e2[2], e1[3] + e2[3])
            r[e] = r.get(e, Fraction(0)) + c1 * c2
    return {e: c for e, c in r.items() if c != 0}


def pdeg(p):
    return max(sum(e) for e in p)


def echelon(rows, ncols):
    """Row-reduce (list of dense Fraction lists) to reduced row echelon form.

    Returns (rows, pivot_columns)."""
    rows = [list(r) for r in rows]
    piv = []
    r = 0
    for c in range(ncols):
        sel = None
        for i in range(r, len(rows)):
            if rows[i][c] != 0:
                sel = i
                break
        if sel is None:
            continue
        rows[r], rows[sel] = rows[sel], rows[r]
        inv = Fraction(1, 1) / rows[r][c]
        rows[r] = [v * inv for v in rows[r]]
        for i in range(len(rows)):
            if i != r and rows[i][c] != 0:
                f = rows[i][c]
                rows[i] = [a - f * b for a, b in zip(rows[i], rows[r])]
        piv.append(c)
        r += 1
        if r == len(rows):
            break
    return rows[:r], piv


def rank(rows, ncols):
    return len(echelon(rows, ncols)[1])


def ideal_degree_rows(gens, d):
    """Dense rows spanning the degree-d piece of the ideal generated by gens."""
    idx = mindex(d)
    rows = []
    for g in gens:
        dg = pdeg(g)
        if dg > d:
            continue
        for m in monomials(d - dg):
            prod = pmul(g, {m: Fraction(1)})
            row = [Fraction(0)] * len(idx)
            for e, c in prod.items():
                row[idx[e]] = c
            rows.append(row)
    return rows


def ideal_dim(gens, d):
    return rank(ideal_degree_rows(gens, d), len(monomials(d)))


def hilbert_function(gens, dmax):
    """HF of S/(gens) in degrees 0..dmax, by exact rank computation."""
    return [len(monomials(d)) - ideal_dim(gens, d) for d in range(dmax + 1)]


# ---- the finite-dimensional algebra A = S/J_S ------------------------------

class Quotient(object):
    """S/(gens) as a graded Q-vector space with an exact normal form."""

    def __init__(self, gens, dmax):
        self.dmax = dmax
        self.ech = {}
        self.pivots = {}
        self.basis_by_deg = {}
        for d in range(dmax + 1):
            ncols = len(monomials(d))
            rows, piv = echelon(ideal_degree_rows(gens, d), ncols)
            self.ech[d] = rows
            self.pivots[d] = piv
            pset = set(piv)
            self.basis_by_deg[d] = [c for c in range(ncols) if c not in pset]
        self.basis = []
        self.offset = {}
        for d in range(dmax + 1):
            self.offset[d] = len(self.basis)
            for c in self.basis_by_deg[d]:
                self.basis.append((d, monomials(d)[c]))
        self.dim = len(self.basis)

    def reduce_degree(self, vec, d):
        """Coordinates of a degree-d vector in the chosen basis of A_d."""
        if d > self.dmax:
            # No echelon form was built above dmax, so nothing can be decided
            # here: refuse rather than silently report the class as zero.
            if any(v != 0 for v in vec):
                raise ValueError("degree %d exceeds dmax=%d; the quotient was "
                                 "not tabulated that far, so this class cannot "
                                 "be reduced" % (d, self.dmax))
            return []
        vec = list(vec)
        for row, c in zip(self.ech[d], self.pivots[d]):
            if vec[c] != 0:
                f = vec[c]
                vec = [a - f * b for a, b in zip(vec, row)]
        return [vec[c] for c in self.basis_by_deg[d]]

    def class_of(self, p):
        """Normal-form coordinate vector (length self.dim) of a polynomial."""
        out = [Fraction(0)] * self.dim
        bydeg = {}
        for e, c in p.items():
            bydeg.setdefault(sum(e), {})[e] = c
        for d, part in bydeg.items():
            if d > self.dmax:
                dense = [Fraction(0)] * len(monomials(d))
                idx = mindex(d)
                for e, c in part.items():
                    dense[idx[e]] = c
                self.reduce_degree(dense, d)   # raises if genuinely nonzero
                continue
            dense = [Fraction(0)] * len(monomials(d))
            idx = mindex(d)
            for e, c in part.items():
                dense[idx[e]] = c
            coords = self.reduce_degree(dense, d)
            for k, v in enumerate(coords):
                out[self.offset[d] + k] = v
        return out

    def mult_matrix(self, f):
        """Rows[j] = coordinates of f * b_j, for basis element b_j."""
        rows = []
        for (d, m) in self.basis:
            rows.append(self.class_of(pmul(f, {m: Fraction(1)})))
        return rows


# ---- Koszul homology H_i(f1,f2,f3 ; A) = Tor_i(S/I_S, S/J_S) --------------
# The Koszul complex on a regular sequence f1,f2,f3 is a free resolution of
# S/I_S, so tensoring it with S/J_S and taking homology yields Tor.

def koszul_matrices(Q, mats):
    n = Q.dim
    zero = [Fraction(0)] * n

    def blk(parts):
        out = []
        for p in parts:
            out.extend(p)
        return out

    # d1 : A^3 -> A      (a e_i |-> f_i a)
    d1 = []
    for i in range(3):
        for j in range(n):
            d1.append(list(mats[i][j]))

    pairs = [(0, 1), (0, 2), (1, 2)]
    # d2 : A^3 (wedge pairs) -> A^3   (a e_i^e_j |-> f_i a e_j - f_j a e_i)
    d2 = []
    for (i, k) in pairs:
        for j in range(n):
            slots = [list(zero), list(zero), list(zero)]
            slots[k] = list(mats[i][j])
            slots[i] = [-v for v in mats[k][j]]
            d2.append(blk(slots))

    # d3 : A -> A^3 (wedge pairs)
    #   a e1^e2^e3 |-> f1 a (e2^e3) - f2 a (e1^e3) + f3 a (e1^e2)
    d3 = []
    signs = [(2, 0, Fraction(1)), (1, 1, Fraction(-1)), (0, 2, Fraction(1))]
    for j in range(n):
        slots = [list(zero), list(zero), list(zero)]
        for slot, fi, sg in signs:
            slots[slot] = [sg * v for v in mats[fi][j]]
        d3.append(blk(slots))
    return d1, d2, d3


def compose(rowsA, rowsB, ncolsB):
    """Matrix product where rows are images of basis vectors."""
    out = []
    for r in rowsA:
        acc = [Fraction(0)] * ncolsB
        for c, v in enumerate(r):
            if v != 0:
                rb = rowsB[c]
                for k in range(ncolsB):
                    if rb[k] != 0:
                        acc[k] += v * rb[k]
        out.append(acc)
    return out


