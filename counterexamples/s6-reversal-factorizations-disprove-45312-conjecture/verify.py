def check_hecke_axioms():
    """The multiplication routine used for every displayed identity is validated
    against the defining relations of H_N(q) before it is trusted.  Without this,
    a bug in hmul would silently reproduce itself on both sides of nothing --
    the identity checks below are only as good as this routine."""
    ident = tuple(range(1, N + 1))
    gen = {}
    for i in range(1, N):
        s = list(ident)
        s[i - 1], s[i] = s[i], s[i - 1]
        gen[i] = tuple(s)

    def T(w):
        return {w: ONE}

    quad = all(hmul(T(gen[i]), T(gen[i]))
               == {ident: QPOLY, gen[i]: QM1} for i in range(1, N))
    braid = all(hmul_all([T(gen[i]), T(gen[j]), T(gen[i])])
                == hmul_all([T(gen[j]), T(gen[i]), T(gen[j])])
                for i in range(1, N) for j in range(1, N) if abs(i - j) == 1)
    commute = all(hmul(T(gen[i]), T(gen[j])) == hmul(T(gen[j]), T(gen[i]))
                  for i in range(1, N) for j in range(1, N) if abs(i - j) > 1)
    ck("hecke_quadratic_and_braid_relations", quad and braid and commute,
       "T_s^2 = q T_e + (q-1) T_s: %s; braid: %s; far generators commute: %s"
       % (quad, braid, commute))

    # T_x T_y = T_{xy} whenever lengths add; and T_e is a two-sided unit.
    perms = list(permutations(range(1, N + 1)))
    addit, cnt = True, 0
    for x in perms:
        for y in perms:
            xy = tuple(x[y[k] - 1] for k in range(N))
            if ell(x) + ell(y) == ell(xy):
                cnt += 1
                if hmul(T(x), T(y)) != T(xy):
                    addit = False
    unit = all(hmul(T(ident), T(x)) == T(x) and hmul(T(x), T(ident)) == T(x)
               for x in perms)
    ck("hecke_length_additivity_and_unit", addit and unit and cnt > 0,
       "T_x T_y = T_{xy} on %d length-additive pairs; T_e is a two-sided unit"
       % cnt)

    # Associativity, and agreement of the two independent code paths:
    # left_mult_s (used to build the KL basis) and hmul (used for the identities).
    sample = sorted(perms, key=ell)[::37]
    assoc = all(hmul(hmul(T(x), T(y)), T(z)) == hmul(T(x), hmul(T(y), T(z)))
                for x in sample for y in sample for z in sample)
    agree = all(hmul(T(gen[i]), {x: (1, -2, 3)}) == left_mult_s({x: (1, -2, 3)}, i)
                for i in range(1, N) for x in perms)
    ck("hecke_associativity_and_left_right_paths_agree", assoc and agree,
       "associative on %d triples; hmul(T_s,.) == left_mult_s on all %d T_x"
       % (len(sample) ** 3, len(perms)))


def check_kl_sanity(C, corr):
    ident = tuple(range(1, N + 1))
    w0 = tuple(range(N, 0, -1))
    ok = True
    for i in range(1, N):
        s = list(ident)
        s[i - 1], s[i] = s[i], s[i - 1]
        s = tuple(s)
        if C[s] != {s: ONE, ident: ONE}:
            ok = False
    ok = ok and len(C[w0]) == 720 and all(p == ONE for p in C[w0].values())
    ck("kl_generators_and_longest_element", ok,
       "Ctilde_s = T_s + T_e for %d generators; Ctilde_w0 = sum of all %d T_v"
       % (N - 1, len(C[w0])))

    bad = []
    for w, el in C.items():
        lw = ell(w)
        if el.get(w) != ONE:
            bad.append((w, "leading"))
        for v, p in el.items():
            if p[0] != 1:
                bad.append((v, w, "const"))
            if v != w and len(p) - 1 > (lw - ell(v) - 1) // 2:
                bad.append((v, w, "degree"))
            if any(c < 0 for c in p):
                bad.append((v, w, "negative"))
    ck("kl_degree_bound_positivity_and_constant_term", not bad,
       "P_{w,w}=1, P_{v,w}(0)=1, coefficients >= 0 (all three derived); "
       "deg P_{v,w} <= (l(w)-l(v)-1)/2 holds by construction, since that bound is "
       "what build_kl_basis strips by, so only the first three can fail here"
       if not bad else "%d violations" % len(bad))

    bad = []
    for w, wp, z, g in corr:
        i = next(k for k in range(1, N) if w.index(k) > w.index(k + 1))
        d = ell(wp) - ell(z)
        monomial = sum(1 for c in g if c != 0) == 1
        if not (monomial and g[-1] > 0 and d % 2 == 1
                and len(g) - 1 == (d + 1) // 2
                and z.index(i) > z.index(i + 1)):
            bad.append((w, z, g))
    ck("kl_mu_corrections_are_positive_monomials", corr and not bad,
       "%d corrections, each mu*q^((l(w')-l(z)+1)/2) with mu>0 and s z < z"
       % len(corr))


