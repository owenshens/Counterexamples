# ----------------------------------------------------------------- Z[q] arithmetic
ZERO = ()
ONE = (1,)


def pnorm(c):
    c = list(c)
    while c and c[-1] == 0:
        c.pop()
    return tuple(c)


def padd(a, b):
    m = max(len(a), len(b))
    return pnorm([(a[i] if i < len(a) else 0) + (b[i] if i < len(b) else 0)
                  for i in range(m)])


def pscale(a, k):
    if k == 0:
        return ZERO
    return pnorm([k * x for x in a])


def pmul(a, b):
    if not a or not b:
        return ZERO
    out = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        if x:
            for j, y in enumerate(b):
                out[i + j] += x * y
    return pnorm(out)


def ppow(a, k):
    r = ONE
    for _ in range(k):
        r = pmul(r, a)
    return r


def qbrack_fact(r):
    """[r]_q! = prod_{k=1}^r (1 + q + ... + q^{k-1}); equals 1 for r in {0,1}."""
    r = int(r)
    out = ONE
    for k in range(1, r + 1):
        out = pmul(out, tuple([1] * k))
    return out


# --------------------------------------------------------- permutations of {1..N}
def ell(w):
    return sum(1 for i in range(len(w)) for j in range(i + 1, len(w)) if w[i] > w[j])


def perm_inverse(w):
    out = [0] * len(w)
    for i, v in enumerate(w):
        out[v - 1] = i + 1
    return tuple(out)


def conj_w0(w):
    n = len(w)
    return tuple(n + 1 - w[n - 1 - i] for i in range(n))


def bruhat_leq(v, w):
    """Standard dot/tableau criterion for v <= w in the Bruhat order."""
    n = len(v)
    for i in range(1, n + 1):
        for j in range(1, n + 1):
            cv = sum(1 for a in range(i) if v[a] >= j)
            cw = sum(1 for a in range(i) if w[a] >= j)
            if cv > cw:
                return False
    return True


def contains_pattern(w, p):
    k = len(p)
    for idx in permutations(range(len(w)), k):
        if list(idx) != sorted(idx):
            continue
        vals = [w[i] for i in idx]
        rank = sorted(range(k), key=lambda t: vals[t])
        rel = [0] * k
        for r, t in enumerate(rank):
            rel[t] = r + 1
        if tuple(rel) == tuple(p):
            return True
    return False


def occurrence_at(w, positions, p):
    """True iff the given 1-based positions of w form an occurrence of pattern p."""
    if list(positions) != sorted(positions) or len(positions) != len(p):
        return False
    vals = [w[i - 1] for i in positions]
    k = len(p)
    rank = sorted(range(k), key=lambda t: vals[t])
    rel = [0] * k
    for r, t in enumerate(rank):
        rel[t] = r + 1
    return tuple(rel) == tuple(p)


# ------------------------------------------------------------- Hecke algebra H_N(q)
# An element is a dict {permutation tuple: Z[q] polynomial}, zero entries pruned.
QPOLY = (0, 1)          # q
QM1 = (-1, 1)           # q - 1


def hadd(X, Y):
    out = dict(X)
    for w, p in Y.items():
        r = padd(out.get(w, ZERO), p)
        if r:
            out[w] = r
        else:
            out.pop(w, None)
    return out


def hscale(X, c):
    out = {}
    for w, p in X.items():
        r = pmul(p, c)
        if r:
            out[w] = r
    return out


def _acc(out, w, p):
    if not p:
        return
    r = padd(out.get(w, ZERO), p)
    if r:
        out[w] = r
    else:
        out.pop(w, None)


def left_mult_s(X, i):
    """T_{s_i} * X.  Left multiplication swaps the VALUES i and i+1."""
    out = {}
    for x, p in X.items():
        y = tuple(i + 1 if v == i else (i if v == i + 1 else v) for v in x)
        if x.index(i) < x.index(i + 1):       # l(s_i x) > l(x)
            _acc(out, y, p)
        else:
            _acc(out, y, pmul(p, QPOLY))
            _acc(out, x, pmul(p, QM1))
    return out


def right_mult_s(X, i):
    """X * T_{s_i}.  Right multiplication swaps POSITIONS i and i+1."""
    out = {}
    for x, p in X.items():
        y = list(x)
        y[i - 1], y[i] = y[i], y[i - 1]
        y = tuple(y)
        if x[i - 1] < x[i]:                   # l(x s_i) > l(x)
            _acc(out, y, p)
        else:
            _acc(out, y, pmul(p, QPOLY))
            _acc(out, x, pmul(p, QM1))
    return out


def hmul(X, Y, n=N):
    """Product X*Y in H_n(q), expanding Y in the T-basis via reduced words."""
    ident = tuple(range(1, n + 1))
    memo = {ident: X}

    def xt(v):
        if v in memo:
            return memo[v]
        for i in range(1, n):
            if v[i - 1] > v[i]:
                vp = list(v)
                vp[i - 1], vp[i] = vp[i], vp[i - 1]
                memo[v] = right_mult_s(xt(tuple(vp)), i)
                return memo[v]
        raise AssertionError("identity handled above")

    out = {}
    for v, p in Y.items():
        for w, r in xt(v).items():
            _acc(out, w, pmul(p, r))
    return out


def hmul_all(factors, n=N):
    out = factors[0]
    for f in factors[1:]:
        out = hmul(out, f, n)
    return out


def build_kl_basis():
    """Ctilde_w for all w in S_N.

    Uses only the defining properties: Ctilde_e = T_e, Ctilde_{s} = T_s + T_e,
    and, for l(s_i w) < l(w) with w' = s_i w, the element Ctilde_{s_i} Ctilde_{w'}
    equals Ctilde_w plus a Z[q]-combination of Ctilde_z with z < w.  The
    combination is pinned down uniquely by the degree bound
    deg P_{z,w} <= (l(w) - l(z) - 1)/2, so we simply strip, from the coefficient
    of each T_z, the part exceeding that bound.  The mu-coefficients are thereby
    derived rather than assumed; CORRECTIONS records them for later inspection.
    """
    ident = tuple(range(1, N + 1))
    perms = sorted(permutations(range(1, N + 1)), key=ell)
    desc = list(reversed(perms))
    C = {ident: {ident: ONE}}
    corrections = []
    for w in perms:
        if w == ident:
            continue
        lw = ell(w)
        i = next(k for k in range(1, N) if w.index(k) > w.index(k + 1))
        wp = tuple(i + 1 if v == i else (i if v == i + 1 else v) for v in w)
        X = hadd(left_mult_s(C[wp], i), C[wp])
        for z in desc:
            if z == w:
                continue
            lz = ell(z)
            if lz >= lw:
                continue
            c = X.get(z, ZERO)
            d = (lw - lz - 1) // 2
            if len(c) <= d + 1:
                continue
            g = pnorm([0] * (d + 1) + list(c[d + 1:]))
            X = hadd(X, hscale(C[z], pscale(g, -1)))
            corrections.append((w, wp, z, g))
        C[w] = X
    return C, corrections


def s_interval(a, b, n=N):
    """Longest element of the parabolic generated by s_a,...,s_{b-1}, inside S_n."""
    w = list(range(1, n + 1))
    w[a - 1:b] = list(reversed(w[a - 1:b]))
    return tuple(w)


def f_A(intervals):
    """f_A(q) computed from the definition, for A = [(a_1,b_1),...,(a_m,b_m)]."""
    sets = [set(range(a, b + 1)) for (a, b) in intervals]
    m = len(sets)
    out = ONE
    for i in range(m):
        for j in range(i + 1, m):
            inter = sets[i] & sets[j]
            for k in range(i + 1, j):
                inter = inter - sets[k]
            out = pmul(out, qbrack_fact(len(inter)))
    return out


