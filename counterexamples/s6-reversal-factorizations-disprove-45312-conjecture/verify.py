def check_prior_work(C):
    C24, C13, C46, C56 = (C[s_interval(2, 4)], C[s_interval(1, 3)],
                          C[s_interval(4, 6)], C[s_interval(5, 6)])

    # PRIOR_A is transcribed from the paper, but it is meant to be the "split" of
    # Larson's resolution data I_0, I_1, I_2 into connected parabolic components.
    # That step is re-derived here rather than taken on trust.
    def components(gens):
        gens = sorted(gens)
        runs, cur = [], [gens[0]]
        for x in gens[1:]:
            if x == cur[-1] + 1:
                cur.append(x)
            else:
                runs.append(cur)
                cur = [x]
        runs.append(cur)
        return [(r[0], r[-1] + 1) for r in runs]

    split = (components(LARSON_I[0]) + components(LARSON_I[1])
             + components(LARSON_I[2]))
    ck("prior_work_interval_sequence_is_the_split_of_larsons_parabolics",
       split == PRIOR_A and all(set(J) == (set(LARSON_I[k - 1]) & set(LARSON_I[k]))
                                for k, J in ((1, LARSON_J[0]), (2, LARSON_J[1]))),
       "connected components of I_0,I_1,I_2 = %s = the displayed sequence; "
       "J_k = I_{k-1} cap I_k" % (str(split),)
       if split == PRIOR_A else "components %s != displayed %s"
       % (str(split), str(PRIOR_A)))

    fa = f_A(PRIOR_A)
    lhs = hscale(Ct(C, "463152"), ppow((1, 1), 4))
    rhs = hmul_all([C[s_interval(a, b)] for (a, b) in PRIOR_A])
    ck("prior_work_split_identity_for_463152",
       fa == ppow((1, 1), 4) and lhs == rhs,
       "f_A=(1+q)^4: %s; (1+q)^4 Ctilde_463152 = C24 C56 C13 C46 C24 C56: %s"
       % (fa == ppow((1, 1), 4), lhs == rhs))

    absorb = (hmul(C56, C46) == hscale(C46, (1, 1))
              and hmul(C46, C56) == hscale(C46, (1, 1)))
    commute = (hmul(C56, C13) == hmul(C13, C56)
               and hmul(C56, C24) == hmul(C24, C56))
    ck("contraction_relations_used_in_the_reduction", absorb and commute,
       "C56 C46 = C46 C56 = (1+q) C46: %s; C56 commutes with C13 and C24: %s"
       % (absorb, commute))


def check_controls(C):
    base = Ct(C, "463152")
    target = hscale(base, ppow((1, 1), 2))
    row1 = hmul_all([C[s_interval(a, b)] for (a, b) in FACTORIZATIONS["463152"]])
    hits = [A for A in CONTROLS
            if hmul_all([C[s_interval(a, b)] for (a, b) in A]) == target]
    other = [ppow((1, 1), k) for k in (1, 3, 4)]
    wrong_pref = [k for k in other if row1 == hscale(base, k)]
    wrong_w = [s for s in FACTORABLE
               if s != "463152" and Ct(C, s) is not None
               and row1 == hscale(Ct(C, s), ppow((1, 1), 2))]
    ck("identity_test_is_sensitive_to_perturbation",
       not hits and not wrong_pref and not wrong_w,
       "%d mutated interval sequences, %d wrong prefactors and %d wrong targets "
       "all rejected" % (len(CONTROLS), len(other), len(FACTORABLE) - 1))

    # Exhaustive single-edit battery over ALL seven rows: delete any one factor,
    # or replace any one factor by any of the other 15 intervals.  A surviving
    # edit would mean the exhibited interval sequence is not what carries the
    # identity.  An edited sequence counts as a survivor as soon as its product
    # equals (1+q)^2 Ctilde_w, whether or not f_A of the edited sequence is still
    # (1+q)^2: the weaker criterion is the one that could expose a non-sharp
    # identity test, so it is the one applied.
    ivs = [(a, b) for a in range(1, N) for b in range(a + 1, N + 1)]
    tgt = ppow((1, 1), 2)
    edits = 0
    survivors = []
    for s in FACTORABLE:
        A = FACTORIZATIONS[s]
        want = hscale(C[perm(s)], tgt)
        for i in range(len(A)):
            edits += 1
            B = A[:i] + A[i + 1:]
            if hmul_all([C[s_interval(a, b)] for (a, b) in B]) == want:
                survivors.append(("delete", s, i))
            for iv in ivs:
                if iv == A[i]:
                    continue
                edits += 1
                B = list(A)
                B[i] = iv
                if hmul_all([C[s_interval(a, b)] for (a, b) in B]) == want:
                    survivors.append(("replace", s, i, iv, f_A(B) == tgt))
    ck("no_single_edit_of_any_exhibited_interval_sequence_survives",
       edits > 0 and not survivors,
       "%d single edits across the 7 rows, none reproduces (1+q)^2 Ctilde_w"
       % edits if not survivors else "survivors: %s" % survivors)

    # The product of each row determines its target uniquely inside all of S_6,
    # not merely among the seven exhibited permutations.
    bad = []
    for s in FACTORABLE:
        P = hmul_all([C[s_interval(a, b)] for (a, b) in FACTORIZATIONS[s]])
        alt = [w for w in C if w != perm(s) and P == hscale(C[w], tgt)]
        if alt:
            bad.append((s, alt))
    ck("each_row_product_matches_no_other_element_of_S6", not bad,
       "for each of the 7 rows, (1+q)^2 Ctilde_v = product for exactly one of the "
       "%d elements v of S_%d" % (len(C), N)
       if not bad else "ambiguous rows: %s" % bad)


def check_corollary(C):
    bad = []
    for n in range(N + 1, N + 4):
        w = perm("463152") + tuple(range(N + 1, n + 1))
        if not contains_pattern(w, PATTERN):
            bad.append(n)
    inside = all(1 <= a < b <= N for (a, b) in FACTORIZATIONS["463152"])
    ck("corollary_embedding_still_contains_45312", not bad and inside,
       "463152 7...n contains 45312 for n=7,8,9 and row 1 uses only s_1..s_%d"
       % (N - 1))

    # The substance of the corollary is that the first factorization survives the
    # parabolic embedding.  That is verified here in H_7 rather than cited.
    M = N + 1
    row1 = FACTORIZATIONS["463152"]
    keys = [perm("463152")] + [s_interval(a, b) for (a, b) in row1]

    # Step 1: for each relevant w in S_6, the Bruhat interval below its image in
    # S_7 is exactly the image of the interval below w in S_6, and lengths agree.
    # Hence no element outside the parabolic can enter, so the Kazhdan-Lusztig
    # recurrence run in S_7 is literally the same computation as in S_6 and
    # Ctilde_{w 7} is the image of Ctilde_w.  This is derived, not assumed.
    full = list(permutations(range(1, M + 1)))
    bad = []
    for w in keys:
        below7 = set(v for v in full if bruhat_leq(v, w + (M,)))
        below6 = set(v + (M,) for v in C if bruhat_leq(v, w))
        if below7 != below6:
            bad.append(w)
    lens = all(ell(v) == ell(v + (M,)) for v in C)
    ck("bruhat_intervals_below_the_embedded_elements_stay_in_the_parabolic",
       not bad and lens,
       "{v in S_%d : v <= w7} = image of {v in S_%d : v <= w} for the %d relevant "
       "w, and l is unchanged by the embedding" % (M, N, len(keys))
       if not bad and lens else "leaks: %s" % bad)

    # Step 2: multiply the four C_{ab} out in H_7 and compare with the embedding.
    def emb(X):
        return {w + (M,): p for w, p in X.items()}

    prod = hmul_all([emb(C[s_interval(a, b)]) for (a, b) in row1], M)
    lhs = hscale(emb(C[perm("463152")]), ppow((1, 1), 2))
    leaks = [w for w in prod if w[M - 1] != M]
    ck("row_one_factorization_holds_verbatim_in_H_7", prod == lhs and not leaks,
       "(1+q)^2 Ctilde_4631527 = C24 C13 C46 C24 computed in H_%d, with no term "
       "outside the parabolic" % M
       if prod == lhs and not leaks else "H_%d identity failed" % M)


