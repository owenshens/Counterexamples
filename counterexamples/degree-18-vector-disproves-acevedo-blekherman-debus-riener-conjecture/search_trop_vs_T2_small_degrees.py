# the total order on partitions of 5 recorded in the source paper (halved coordinates give the
# same statement on Lambda_5)
CHAIN5 = [(1, 1, 1, 1, 1), (2, 1, 1, 1), (3, 1, 1), (2, 2, 1), (4, 1), (3, 2), (5,)]
# recorded in the source paper: valid on trop(BP_10^*), NOT valid on trop(BSigma_10^*)
EXTRA_BP10 = {(1, 1, 1, 1, 1): 1, (3, 2): 1, (4, 1): 1, (3, 1, 1): -3}

def densify(d, dct):
    coords = partitions(d)
    idx = {p: i for i, p in enumerate(coords)}
    v = [0] * len(coords)
    for p, c in dct.items():
        v[idx[p]] += c
    return v

# ---------------------------------------------------------------- controls

def control_chain():
    print("[CTRL-1 published total order on partitions of 5]")
    ok = True
    for i in range(len(CHAIN5) - 1):
        a, b = CHAIN5[i], CHAIN5[i + 1]
        s = superdom(a, b) and not superdom(b, a)
        ok = ok and s
        print("   %s succ %s : %s" % (a, b, s))
    tot = all(superdom(x, y) or superdom(y, x) for x in partitions(5) for y in partitions(5))
    print("   total order on Lambda_5 : %s  (paper: yes)" % tot)
    bad = [(x, y) for x in partitions(6) for y in partitions(6)
           if not superdom(x, y) and not superdom(y, x)]
    print("   Lambda_6 incomparable pairs : %d  (paper: not a total order for d>=6)" % (len(bad) // 2))
    print("   e.g. %s" % (bad[:6],))
    print("   CTRL-1 %s" % ("PASS" if (ok and tot and bad) else "FAIL"))
    return ok and tot and bool(bad)

def control_published_facets(d, singletons):
    coords, A, provA = trop_generators(d, singletons)
    okall = True
    for (name, dct) in L[d]:
        g = densify(d, dct)
        f, cert = in_cone(A, g)
        if not f:
            okall = False
        print("   L_%d member in cone(A): %-42s %s" % (d - 1, name, f))
    Lrows = [densify(d, dct) for (_, dct) in L[d]]
    for j, r in enumerate(A):
        f, cert = in_cone(Lrows, r)
        if not f:
            okall = False
            print("   *** A row NOT implied by published L_%d: %s" % (d - 1, provA[j]))
    print("   CTRL-2 d=%d (|A|=%d, singleton-type1=%s): %s"
          % (d, len(A), singletons, "PASS (cones equal)" if okall else "FAIL"))
    return okall

def control_forced_positive(d, singletons):
    """(a) reversed strict order inequality must be REFUSED with a verified witness
       (b) published trop(BP_10^*) extra facet must be REFUSED at d=5"""
    coords, A, provA = trop_generators(d, singletons)
    ok = True
    # (a) find a strict superdominance pair and reverse it
    ps = partitions(d)
    for x in ps:
        for y in ps:
            if x != y and superdom(x, y):
                g = [0] * len(ps)
                g[ps.index(y)] += 1
                g[ps.index(x)] -= 1        # y_y >= y_x  -- must NOT be valid
                f, cert = in_cone(A, g)
                if f:
                    print("   *** FORCED-POSITIVE FAILED: reversed %s>=%s accepted" % (y, x))
                    ok = False
                else:
                    c1, val = check_witness(A, g, cert)
                    if not (c1 and val < 0):
                        print("   *** witness verification failed on reversed pair")
                        ok = False
                break
        break
    print("   CTRL-3a reversed-order inequality refused with verified witness: %s" % ok)
    if d == 5:
        g = densify(5, EXTRA_BP10)
        f, cert = in_cone(A, g)
        if f:
            print("   *** CTRL-3b FAILED: published trop(BP_10^*)-only facet accepted on trop(BSigma_10^*)")
            ok = False
        else:
            c1, val = check_witness(A, g, cert)
            print("   CTRL-3b published trop(BP_10^*) extra facet y(1^5)+y(3,2)+y(4,1) >= 3y(3,1,1)"
                  " refused: True; witness verified: %s, value %s" % (c1, val))
            print("      witness y = %s" % dict(zip(partitions(5), cert)))
            ok = ok and c1 and val < 0
    return ok

def control_proved_inclusion(d, singletons):
    """The source paper's theorem T^(2) subset trop, i.e. EVERY row of A is implied by B."""
    coords, A, provA = trop_generators(d, singletons)
    _, B, provB = T2_generators(d)
    bad = []
    for j, r in enumerate(A):
        f, _ = in_cone(B, r)
        if not f:
            bad.append(provA[j])
    print("   CTRL-4 d=%d PROVED inclusion T^(2) subset trop  (|A|=%d,|B|=%d): %s"
          % (d, len(A), len(B), "PASS" if not bad else "FAIL"))
    for b in bad[:8]:
        print("      *** A row not implied by T^(2): %s" % b)
    return not bad

# ---------------------------------------------------------------- main decision

def decide(d, singletons):
    coords, A, provA = trop_generators(d, singletons)
    _, B, provB = T2_generators(d)
    print("=== DECIDE d=%d : |coords|=%d  |A(trop gens)|=%d  |B(T2 gens)|=%d  singleton-type1=%s"
          % (d, len(coords), len(A), len(B), singletons))
    viol = []
    for j, g in enumerate(B):
        f, cert = in_cone(A, g)
        if not f:
            ok, val = check_witness(A, g, cert)
            viol.append((provB[j], cert, ok, val))
    print("    T^(2) generators tested: %d / %d  (EXHAUSTION = %d/%d = 1)"
          % (len(B), len(B), len(B), len(B)))
    print("    NOT implied by trop's generators: %d" % len(viol))
    for (why, cert, ok, val) in viol[:12]:
        print("    *** %s" % why)
        print("        witness verified in trop: %s   value g.y = %s" % (ok, val))
        print("        y = %s" % dict(zip(coords, cert)))
    return len(A), len(B), viol, coords, A, provA

