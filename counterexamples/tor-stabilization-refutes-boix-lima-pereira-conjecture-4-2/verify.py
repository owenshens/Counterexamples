#!/usr/bin/env python3
"""Verification of a counterexample to a conjectured Tor-length identity.

The conjecture under test: for a regular local ring (R,m) of dimension n, an
ideal I generated by an R-regular sequence of length k, and an ideal J
generated by an R-regular sequence of length n, with the restriction
k <= n-1,
        length(Tor_i^R(R/I, R/J)) = binom(k,i) * length(R/(I+J)),  0<=i<=k.

VALUES TAKEN FROM THE PAPER (inputs; this program does not re-derive them)
  * the ring R = Q[x,y,z,t] localized at (x,y,z,t), so n = 4;
  * I = (x^2, y^2, z^2)  and  J = (x^2+xy, xz+z^2, y^2+yz, t), so k = 3;
  * the statement of the identity displayed above, including its hypotheses;
  * the asserted Groebner basis of J_0 = (x^2+xy, xz+z^2, y^2+yz) for graded
    reverse lexicographic order with x > y > z, and the asserted monomial
    basis 1; x,y,z; xy,yz,z^2; z^3 of A = Q[x,y,z]/J_0;
  * the asserted pairing matrix T with rows (1,-1,1),(1,1,-1),(-1,1,1) and
    det T = 4;
  * the asserted chain dimensions 8,24,24,8, differential ranks 4,6,4 and
    their graded pieces (3,1),(3,3),(1,3);
  * the asserted Tor-length vector (4,14,14,4), colength 4 and conjectured
    vector (4,12,12,4);
  * the two cited results making the identity true for k <= 2, used only to
    phrase the minimality of the pair (n,k) = (4,3).

DERIVED HERE (computed from the generators by exact rational arithmetic)
  * normal forms in A by row reducing every graded piece of J_0; the Hilbert
    function (1,3,3,1,0), hence colength 8 and (x,y,z)^4 in J_0.  Three forms
    in three variables with finite colength have codimension 3, so both
    triples of generators are regular sequences;
  * that the five asserted Groebner basis elements lie in J_0 and that their
    leading terms generate the initial ideal of J_0 in every degree through 6,
    which certifies the asserted basis and its 8 standard monomials;
  * the multiplication matrix of A_2 (x) A_1 -> A_3 and its determinant;
  * the three differentials of the Koszul complex K(x^2,y^2,z^2; A) as
    explicit rational matrices, that consecutive ones compose to zero, their
    exact ranks, their graded ranks, and the homology dimensions;
  * length(R/(I+J)) as dim A - rank d_1, and the ideal of A that it kills;
  * the conjectured vector binom(3,i)*colength and the exact set of indices
    where the computed vector differs from it: this is the refutation;
  * the same Tor vector recomputed from scratch in Q[x,y,z,t] and in
    Q[x,y,z,t1,t2], i.e. for gaps n-k = 1 and n-k = 2, which exercises the
    stabilization statement in the cases the argument uses;
  * a census over four graded complete intersections in three variables and
    five regular sequences: 20 instances each for k = 1, 2, 3, together with
    a control off the hypotheses.  The census is in three variables, so
    n = 3 in all of it: the k = 1 and k = 2 instances are in the range
    k <= n-1 of the conjecture under test, while the k = 3 instances have
    k = n and belong to the unrestricted assertion already disproved in the
    cited literature.  The k = 3 failures the census reports are therefore
    not additional counterexamples to the k <= n-1 conjecture; they reach
    its range only through stabilization.  The control matters: for k = 1 the
    identity is rank-nullity and holds for every element of every finite
    dimensional algebra, so no k = 1 instance can ever fail and that half of
    the census carries no information.  For k = 2 the identity is equivalent
    to rank d_1 = rank d_2; dropping only the complete intersection
    hypothesis on R/J breaks it, which is what the control exhibits, so the
    k = 2 half is discriminating.  The minimality check is conditioned on
    both, and fails rather than restating the claim if either collapses.

Because R/J is isomorphic to A, which is a graded Artinian local Q-algebra
with residue field Q, Tor_i^R(R/I,R/J) is the i-th homology of the Koszul
complex of x^2,y^2,z^2 over A, localization is inert, and lengths over R are
Q-vector space dimensions.

Standard library only; every decision is made with integers or fractions.
"""

import sys
from fractions import Fraction
from itertools import combinations

CHECKS = []
CENSUS = {}
Q0 = Fraction(0)
Q1 = Fraction(1)


# ---------------------------------------------------------------- polynomials
# A polynomial in nv variables is a dict {exponent tuple: Fraction}, 0 omitted.

def p_clean(p):
    return dict((m, c) for m, c in p.items() if c != 0)


def p_mul(p, q):
    r = {}
    for m1, c1 in p.items():
        for m2, c2 in q.items():
            m = tuple(a + b for a, b in zip(m1, m2))
            r[m] = r.get(m, Q0) + c1 * c2
    return p_clean(r)


def p_degree(p):
    return max(sum(m) for m in p) if p else -1


def p_homogeneous(p):
    return len(set(sum(m) for m in p)) <= 1


def mons(nv, d):
    """All exponent tuples in nv variables of total degree exactly d."""
    if nv == 1:
        return [(d,)]
    out = []
    for e in range(d, -1, -1):
        for rest in mons(nv - 1, d - e):
            out.append((e,) + rest)
    # descending graded reverse lexicographic order
    out.sort(key=lambda m: tuple(reversed(m)))
    return out


def grevlex_gt(a, b):
    """Graded reverse lexicographic order, first variable largest."""
    if sum(a) != sum(b):
        return sum(a) > sum(b)
    for i in range(len(a) - 1, -1, -1):
        if a[i] != b[i]:
            return a[i] < b[i]
    return False


def p_str(p, names):
    if not p:
        return "0"
    order = sorted(p.keys(), key=lambda m: (-sum(m), tuple(reversed(m))))
    out = ""
    for m in order:
        c = p[m]
        piece = "*".join(names[i] + ("^%d" % e if e > 1 else "")
                         for i, e in enumerate(m) if e)
        if not piece:
            piece = "1"
        if abs(c) != 1 or piece == "1":
            piece = ("%s*" % abs(c)) + piece if piece != "1" else str(abs(c))
        out += (" - " if c < 0 else (" + " if out else "")) + piece
    return out.strip()


def det(mat):
    n = len(mat)
    m = [list(r) for r in mat]
    d = Q1
    for c in range(n):
        pr = None
        for i in range(c, n):
            if m[i][c] != 0:
                pr = i
                break
        if pr is None:
            return Q0
        if pr != c:
            m[c], m[pr] = m[pr], m[c]
            d = -d
        d *= m[c][c]
        inv = Q1 / m[c][c]
        for i in range(c + 1, n):
            if m[i][c] != 0:
                f = m[i][c] * inv
                m[i] = [a - f * b for a, b in zip(m[i], m[c])]
    return d


def binom(n, i):
    r = 1
    for j in range(i):
        r = r * (n - j) // (j + 1)
    return r


def leading_monomial(p):
    lm = None
    for m in p:
        if lm is None or grevlex_gt(m, lm):
            lm = m
    return lm


def ck(name, ok, detail=""):
    CHECKS.append((name, bool(ok)))
    tag = "PASS" if ok else "FAIL"
    if detail:
        print("%s %s [%s]" % (tag, name, detail))
    else:
        print("%s %s" % (tag, name))
    return bool(ok)


def finish():
    n = len(CHECKS)
    bad = [nm for nm, ok in CHECKS if not ok]
    if bad:
        print("VERDICT: %d OF %d CHECKS FAILED" % (len(bad), n))
        sys.exit(1)
    print("VERDICT: ALL %d CHECKS PASS" % n)
    sys.exit(0)


# ------------------------------------------------------- exact linear algebra

def rref(rows, ncols):
    """Reduced row echelon form over Q.  Returns (rows, pivot column list)."""
    mat = [list(r) for r in rows]
    pivots = []
    r = 0
    for c in range(ncols):
        pr = None
        for i in range(r, len(mat)):
            if mat[i][c] != 0:
                pr = i
                break
        if pr is None:
            continue
        mat[r], mat[pr] = mat[pr], mat[r]
        inv = Q1 / mat[r][c]
        mat[r] = [v * inv for v in mat[r]]
        for i in range(len(mat)):
            if i != r and mat[i][c] != 0:
                f = mat[i][c]
                mat[i] = [a - f * b for a, b in zip(mat[i], mat[r])]
        pivots.append(c)
        r += 1
        if r == len(mat):
            break
    return mat[:r], pivots


def rank(rows, ncols):
    return len(rref(rows, ncols)[1])


def in_rowspace(rows, vec, ncols):
    """True iff vec lies in the span of rows."""
    return rank(list(rows) + [list(vec)], ncols) == rank(rows, ncols)


def ideal_piece(gens, nv, d):
    """Rows spanning the degree-d part of the homogeneous ideal (gens)."""
    basis = mons(nv, d)
    idx = dict((m, i) for i, m in enumerate(basis))
    rows = []
    for g in gens:
        e = p_degree(g)
        if e < 0 or e > d:
            continue
        for m in mons(nv, d - e):
            v = [Q0] * len(basis)
            for mg, c in g.items():
                v[idx[tuple(a + b for a, b in zip(m, mg))]] += c
            rows.append(v)
    return basis, idx, rows


class GradedQuotient(object):
    """S/(homogeneous gens) as a graded Q-vector space with normal forms.

    Per degree d the ideal piece is row reduced; pivot monomials are rewritten
    in terms of the non-pivot ones, which form a basis of the degree-d part.
    If some A_d = 0 then A_e = 0 for all e >= d, because S is generated in
    degree 1, so stopping at the first vanishing degree loses nothing.
    """

    def __init__(self, gens, nv, dmax=9):
        self.nv = nv
        self.gens = gens
        self.basis = {}
        self.red = {}
        self.artinian = False
        d = 0
        while d <= dmax:
            mlist, idx, rows = ideal_piece(gens, nv, d)
            red_rows, pivots = rref(rows, len(mlist))
            piv = set(pivots)
            nonpiv = [j for j in range(len(mlist)) if j not in piv]
            self.basis[d] = [mlist[j] for j in nonpiv]
            table = {}
            for pos, j in enumerate(nonpiv):
                v = [Q0] * len(nonpiv)
                v[pos] = Q1
                table[mlist[j]] = v
            for ri, c in enumerate(pivots):
                table[mlist[c]] = [-red_rows[ri][j] for j in nonpiv]
            self.red[d] = table
            if not self.basis[d]:
                self.artinian = True
                self.top = d - 1
                break
            d += 1
        if not self.artinian:
            self.top = dmax
        self.flat = []
        for e in range(self.top + 1):
            for m in self.basis[e]:
                self.flat.append((e, m))
        self.fidx = dict((k, i) for i, k in enumerate(self.flat))
        self.dim = len(self.flat)

    def hilbert(self):
        return [len(self.basis.get(d, [])) for d in range(self.top + 2)]

    def vec_of_poly(self, p):
        v = [Q0] * self.dim
        for m, c in p.items():
            d = sum(m)
            if d > self.top:
                continue
            for t, val in enumerate(self.red[d][m]):
                if val:
                    v[self.fidx[(d, self.basis[d][t])]] += c * val
        return v

    def mult_matrix(self, f):
        """Matrix of multiplication by homogeneous f on A, flat basis."""
        e = p_degree(f)
        M = [[Q0] * self.dim for _ in range(self.dim)]
        for j, (d, m) in enumerate(self.flat):
            dd = d + e
            if dd > self.top:
                continue
            for mg, c in f.items():
                mm = tuple(a + b for a, b in zip(m, mg))
                for t, val in enumerate(self.red[dd][mm]):
                    if val:
                        M[self.fidx[(dd, self.basis[dd][t])]][j] += c * val
        return M


class Koszul(object):
    """Koszul complex K(f_1,...,f_k; A) of an Artinian graded algebra A."""

    def __init__(self, A, fs):
        self.A = A
        self.k = len(fs)
        self.N = A.dim
        self.mats = [A.mult_matrix(f) for f in fs]
        self.wedge = dict((i, list(combinations(range(self.k), i)))
                          for i in range(self.k + 1))
        self.dims = dict((i, len(self.wedge[i]) * self.N)
                         for i in range(self.k + 1))
        self.d = {}
        for i in range(1, self.k + 1):
            nc = self.dims[i]
            nr = self.dims[i - 1]
            pos = dict((T, t) for t, T in enumerate(self.wedge[i - 1]))
            mat = [[Q0] * nc for _ in range(nr)]
            for ti, T in enumerate(self.wedge[i]):
                for l in range(i):
                    ts = pos[T[:l] + T[l + 1:]]
                    sgn = Q1 if l % 2 == 0 else -Q1
                    Mq = self.mats[T[l]]
                    for j in range(self.N):
                        col = ti * self.N + j
                        for r in range(self.N):
                            v = Mq[r][j]
                            if v:
                                mat[ts * self.N + r][col] += sgn * v
            self.d[i] = mat
        self.ranks = dict((i, rank(self.d[i], self.dims[i]))
                          for i in range(1, self.k + 1))

    def homology(self):
        h = []
        for i in range(self.k + 1):
            r_in = self.ranks.get(i + 1, 0)
            r_out = self.ranks.get(i, 0)
            h.append(self.dims[i] - r_out - r_in)
        return h

    def composites_vanish(self):
        for i in range(1, self.k):
            lo, hi = self.d[i], self.d[i + 1]
            for r in range(len(lo)):
                for c in range(self.dims[i + 1]):
                    s = Q0
                    for t in range(self.dims[i]):
                        if lo[r][t] and hi[t][c]:
                            s += lo[r][t] * hi[t][c]
                    if s != 0:
                        return False
        return True

    def graded_rank(self, i, e):
        """Rank of d_i restricted to A_e (x) wedge^i; the map is graded."""
        cols = [ti * self.N + j
                for ti in range(len(self.wedge[i]))
                for j in range(self.N) if self.A.flat[j][0] == e]
        sub = [[row[c] for c in cols] for row in self.d[i]]
        return rank(sub, len(cols))


