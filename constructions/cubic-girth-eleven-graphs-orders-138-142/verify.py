def decode_graph6(text):
    """Decode a graph6 string into (n, adjacency list of sets, sorted edge list)."""
    s = text.strip()
    for ch in s:
        if not (63 <= ord(ch) <= 126):
            raise ValueError("byte outside the graph6 alphabet")
    val = [ord(ch) - 63 for ch in s]
    if val[0] == 63:                      # '~' prefix: 18-bit order field
        n = (val[1] << 12) | (val[2] << 6) | val[3]
        body = val[4:]
    else:
        n = val[0]
        body = val[1:]
    need = n * (n - 1) // 2
    if len(body) != (need + 5) // 6:
        raise ValueError("graph6 payload is %d bytes, order %d needs %d"
                         % (len(body), n, (need + 5) // 6))
    bits = []
    for x in body:
        for k in (5, 4, 3, 2, 1, 0):
            bits.append((x >> k) & 1)
    for extra in bits[need:]:             # padding must be zero
        if extra:
            raise ValueError("non-zero graph6 padding bit")
    adj = [set() for _ in range(n)]
    edges = []
    pos = 0
    for j in range(1, n):
        for i in range(j):
            if bits[pos]:
                adj[i].add(j)
                adj[j].add(i)
                edges.append((i, j))
            pos += 1
    return n, adj, edges


def bfs_dist(adj, src):
    """Exact integer BFS distances from src; -1 for a vertex not reached."""
    dist = [-1] * len(adj)
    dist[src] = 0
    queue = deque([src])
    while queue:
        u = queue.popleft()
        for w in adj[u]:
            if dist[w] < 0:
                dist[w] = dist[u] + 1
                queue.append(w)
    return dist


def is_connected(adj):
    if not adj:
        return False
    return all(d >= 0 for d in bfs_dist(adj, 0))


def degree_multiset(adj):
    return sorted(len(a) for a in adj)


def girth(adj):
    """Exact girth by BFS from every vertex; None if the graph is a forest.

    For a root r, every non-tree edge (u, w) both of whose ends are reached
    yields the closed walk r..u-w..r of length dist[u]+dist[w]+1; taking the
    minimum over all roots gives the girth exactly.
    """
    best = None
    for root in range(len(adj)):
        parent = [-1] * len(adj)
        dist = [-1] * len(adj)
        dist[root] = 0
        queue = deque([root])
        while queue:
            u = queue.popleft()
            if best is not None and 2 * dist[u] >= best:
                continue
            for w in adj[u]:
                if dist[w] < 0:
                    dist[w] = dist[u] + 1
                    parent[w] = u
                    queue.append(w)
                elif w != parent[u]:
                    cand = dist[u] + dist[w] + 1
                    if best is None or cand < best:
                        best = cand
    return best


def check_tooling():
    """Self-test of the girth routine on graphs whose girth is textbook."""
    k4 = [{1, 2, 3}, {0, 2, 3}, {0, 1, 3}, {0, 1, 2}]
    pet_pairs = [(0, 1), (1, 2), (2, 3), (3, 4), (4, 0),
                 (5, 7), (7, 9), (9, 6), (6, 8), (8, 5),
                 (0, 5), (1, 6), (2, 7), (3, 8), (4, 9)]
    pet = [set() for _ in range(10)]
    for a, b in pet_pairs:
        pet[a].add(b)
        pet[b].add(a)
    hea = [set() for _ in range(14)]
    for i in range(14):
        hea[i].add((i + 1) % 14)
        hea[(i + 1) % 14].add(i)
    for i in range(0, 14, 2):             # LCF notation [5, -5]^7
        hea[i].add((i + 5) % 14)
        hea[(i + 5) % 14].add(i)
    tree = [{1}, {0, 2}, {1}]
    got = (girth(k4), girth(pet), girth(hea), girth(tree))
    ck("girth_routine_selftest", got == (3, 5, 6, None),
       "K4/Petersen/Heawood/path -> %s, want (3, 5, 6, None)" % (got,))


def check_decoder_selftest():
    """Self-test of the graph6 decoder on strings written out by hand.

    The bit order is (0,1),(0,2),(1,2),... six bits per byte, most significant
    first, each byte offset by 63.  So on three vertices the empty graph is
    'B?' (000000), the path 0-1-2 is 'Bg' (101000 = 40) and the triangle is
    'Bw' (111000 = 56).  A '~' introduces an 18-bit order field, so an order of
    63 is written '~??~' and needs ceil(63*62/2/6) = 326 payload bytes.
    """
    empty = decode_graph6("B?")
    path = decode_graph6("Bg")
    tri = decode_graph6("Bw")
    wide = decode_graph6("~??~" + "?" * 326)
    got = (empty[0], empty[2], path[0], path[2], degree_multiset(path[1]),
           tri[0], tri[2], girth(tri[1]), wide[0], wide[2])
    want = (3, [], 3, [(0, 1), (1, 2)], [1, 1, 2],
            3, [(0, 1), (0, 2), (1, 2)], 3, 63, [])
    ck("graph6_decoder_selftest", got == want,
       "hand-written strings B?/Bg/Bw/'~??~' decode to %s, want %s"
       % (got, want))


def check_transcription(name, text, key, order, size):
    n, adj, edges = decode_graph6(text)
    dig = hashlib.sha256(text.encode("ascii")).hexdigest()
    ok = (n == order and len(edges) == size and dig == DIGESTS[key])
    ck("transcription_" + name, ok,
       "order %d, %d edges, sha256 %s..." % (n, len(edges), dig[:16]))
    return n, adj, edges


def check_simple(name, adj):
    loops = [v for v in range(len(adj)) if v in adj[v]]
    asym = [(u, w) for u in range(len(adj)) for w in adj[u] if u not in adj[w]]
    oob = [(u, w) for u in range(len(adj)) for w in adj[u]
           if not (0 <= w < len(adj))]
    ck("simple_" + name, not loops and not asym and not oob,
       "loop-free, symmetric adjacency, all endpoints in range"
       if not (loops or asym or oob) else
       "loops %s, asymmetric %s, out of range %s" % (loops[:3], asym[:3], oob[:3]))


def check_cubic_connected(name, adj, order, size, want_girth):
    degs = degree_multiset(adj)
    cubic = degs == [3] * order
    ck("cubic_" + name, cubic and len(adj) == order,
       "degree multiset is %d copies of 3" % order if cubic else "degrees %s" % (
           sorted(set(degs)),))
    ck("connected_" + name, is_connected(adj), "BFS reaches all %d vertices" % order)
    g = girth(adj)
    ck("girth_%s_is_%d" % (name, want_girth), g == want_girth,
       "computed girth %s, paper says %d" % (g, want_girth))
    edge_count = sum(len(a) for a in adj) // 2
    ck("size_" + name, edge_count == size,
       "%d edges (3*%d/2 = %d)" % (edge_count, order, 3 * order // 2))


def subdivide_and_join(adj140, e1, e2, x, y):
    """Technique 1: subdivide e1 by x, subdivide e2 by y, add the edge xy."""
    a, b = e1
    c, d = e2
    new = [set(s) for s in adj140] + [set(), set()]
    new[a].discard(b)
    new[b].discard(a)
    new[c].discard(d)
    new[d].discard(c)
    for u in (a, b):
        new[u].add(x)
        new[x].add(u)
    for u in (c, d):
        new[u].add(y)
        new[y].add(u)
    new[x].add(y)
    new[y].add(x)
    return new


def delete_two_edges(adj140, e1, e2):
    out = [set(s) for s in adj140]
    for u, v in (e1, e2):
        out[u].discard(v)
        out[v].discard(u)
    return out


def check_142_hypotheses(adj140):
    a, b = E1
    c, d = E2
    ok = (b in adj140[a]) and (d in adj140[c]) and len({a, b, c, d}) == 4
    ck("e1_e2_are_disjoint_edges_of_G140", ok,
       "e1=%s, e2=%s both present and vertex-disjoint" % (sorted(E1), sorted(E2)))
    minus = delete_two_edges(adj140, E1, E2)
    dists = {}
    for u in (a, b):
        row = bfs_dist(minus, u)
        for v in (c, d):
            dists[(u, v)] = row[v]
    ck("dist_in_G140_minus_e1_e2_all_8", set(dists.values()) == {8},
       "distances %s, paper says 8 for all four pairs"
       % (sorted(dists.items()),))
    return minus


def cycle_edges(cyc):
    return [frozenset((cyc[i], cyc[(i + 1) % len(cyc)])) for i in range(len(cyc))]


def is_cycle(adj, cyc):
    if len(set(cyc)) != len(cyc):
        return False
    return all(sorted(e)[1] in adj[sorted(e)[0]] for e in cycle_edges(cyc))


def check_142_conclusion(adj142):
    ck("g142_exhibited_11cycle", is_cycle(adj142, CYCLE_142) and len(CYCLE_142) == 11,
       "the listed closed walk is a cycle on %d distinct vertices" % len(set(CYCLE_142)))
    es = set(cycle_edges(CYCLE_142))
    avoids = (frozenset(E1) not in es and frozenset(E2) not in es
              and X not in CYCLE_142 and Y not in CYCLE_142)
    ck("g142_11cycle_avoids_e1_e2_x_y", avoids,
       "the exhibited 11-cycle uses neither e1, e2, x nor y, so it survives "
       "the subdivision as claimed")


def check_142_through_xy(adj142):
    """Paper: a cycle avoiding the edge xy but using x or y has length >= 12."""
    stripped = [set(s) for s in adj142]
    stripped[X].discard(Y)
    stripped[Y].discard(X)
    lens = []
    for v, pair in ((X, E1), (Y, E2)):
        cut = [set(s) for s in stripped]
        for w in list(cut[v]):
            cut[w].discard(v)
        cut[v] = set()
        lens.append(bfs_dist(cut, pair[0])[pair[1]] + 2)
    ck("g142_cycles_through_x_or_y_but_not_the_edge_xy_at_least_12",
       min(lens) >= 12,
       "with the edge xy deleted, the shortest cycle through x is %d and the "
       "shortest cycle through y is %d (paper: >= 12 for a cycle that uses x "
       "or y and avoids xy; a cycle using xy can have length 11)"
       % (lens[0], lens[1]))


def check_142_negative_control(adj140):
    """A critic's perturbation: subdivide two edges that are close together."""
    bad = subdivide_and_join(adj140, (0, 1), (56, 57), X, Y)
    g = girth(bad)
    ck("g142_negative_control", g is not None and g < 11,
       "subdividing {0,1} and {56,57} instead gives girth %s, so the girth "
       "routine is not reporting 11 unconditionally" % (g,))


def excise(adj152, removed):
    """Return (kept labels, index map, H as an indexed adjacency list)."""
    gone = set(removed)
    kept = [v for v in range(len(adj152)) if v not in gone]
    idx = {v: i for i, v in enumerate(kept)}
    hh = [set(idx[w] for w in adj152[v] if w not in gone) for v in kept]
    return kept, idx, hh


def check_138_hypotheses(adj152):
    ck("excised_set_S_is_a_14_set_of_vertices",
       len(S_EXCISED) == len(set(S_EXCISED)) == 14
       and all(0 <= v < 152 for v in S_EXCISED),
       "|S| = %d, all labels in [0,152)" % len(set(S_EXCISED)))
    kept, idx, hh = excise(adj152, S_EXCISED)
    ck("H_has_order_138", len(kept) == 138,
       "152 - 14 = %d vertices remain" % len(kept))
    two = sorted(kept[i] for i in range(len(kept)) if len(hh[i]) == 2)
    others = sorted(set(len(hh[i]) for i in range(len(kept))
                        if kept[i] not in set(D_DEG2)))
    ck("H_degree_two_set_is_exactly_D", two == sorted(D_DEG2) and others == [3],
       "degree-2 vertices %s; every other vertex has degree %s"
       % ("match D (16 of them)" if two == sorted(D_DEG2) else two, others))
    return kept, idx, hh


def check_matching(idx, hh):
    flat = [v for e in MATCHING for v in e]
    absent = sorted(set(v for v in flat if v not in idx))
    perfect = (len(MATCHING) == 8 and len(flat) == len(set(flat)) == 16
               and set(flat) == set(D_DEG2) and not absent)
    ck("M_is_a_perfect_matching_on_D", perfect,
       "8 pairwise disjoint pairs covering all 16 degree-2 vertices"
       if perfect else "pairs %s, endpoints missing from H: %s"
       % (MATCHING, absent))
    if absent:
        for nm in ("M_edges_absent_from_H", "dist_H_across_each_M_edge_is_10",
                   "dist_H_between_distinct_M_edges_at_least_5"):
            ck(nm, False, "not evaluable: M touches excised vertices %s" % absent)
        return
    already = [e for e in MATCHING if idx[e[1]] in hh[idx[e[0]]]]
    ck("M_edges_absent_from_H", not already,
       "no edge of M already lies in H, so G138 is simple"
       if not already else "already present: %s" % already)
    inner = [bfs_dist(hh, idx[u])[idx[v]] for u, v in MATCHING]
    ck("dist_H_across_each_M_edge_is_10", set(inner) == {10},
       "the eight distances are %s, paper says 10" % (inner,))
    cross = []
    for i in range(len(MATCHING)):
        for j in range(i + 1, len(MATCHING)):
            for u in MATCHING[i]:
                row = bfs_dist(hh, idx[u])
                for v in MATCHING[j]:
                    cross.append(row[idx[v]])
    ck("dist_H_between_distinct_M_edges_at_least_5",
       cross and min(cross) >= 5,
       "minimum over the %d cross pairs is %d, paper says >= 5"
       % (len(cross), min(cross)))


def add_matching(hh, idx, matching):
    out = [set(s) for s in hh]
    for u, v in matching:
        out[idx[u]].add(idx[v])
        out[idx[v]].add(idx[u])
    return out


def check_138_conclusion(g138, idx):
    gone = sorted(set(v for v in CYCLE_138 if v not in idx))
    if gone:
        ck("g138_exhibited_11cycle", False,
           "cycle names vertices absent from G138: %s" % gone)
        ck("g138_11cycle_meets_M_in_exactly_one_edge", False,
           "not evaluable: cycle names excised vertices %s" % gone)
        return
    orig = [idx[v] for v in CYCLE_138]
    ok = is_cycle(g138, orig) and len(CYCLE_138) == 11
    ck("g138_exhibited_11cycle", ok,
       "the listed closed walk is a cycle on %d distinct vertices"
       % len(set(CYCLE_138)))
    mset = set(frozenset(e) for e in MATCHING)
    used = [sorted(e) for e in cycle_edges(CYCLE_138) if e in mset]
    ck("g138_11cycle_meets_M_in_exactly_one_edge",
       used == [[135, 141]],
       "the cycle's edges in M are %s, paper says only {135,141}" % (used,))


def check_138_negative_control(hh, idx):
    """A critic's perturbation: rewire two matching edges across each other."""
    bad = [e for e in MATCHING if e not in ((112, 118), (134, 140))]
    bad = bad + [(112, 134), (118, 140)]
    g = girth(add_matching(hh, idx, bad))
    ck("g138_negative_control", g is not None and g < 11,
       "rewiring M to {112,134},{118,140} gives girth %s, so the girth 11 "
       "verdict depends on the exhibited matching" % (g,))


def check_biggs_arithmetic(src_order, src_girth, excised, out_order, out_girth):
    """epsilon(g) = 2^(r+1) - 2 for g = 4r or 4r + 1, applied to what was built.

    Every quantity here is a computed one: the girth of the source graph, the
    size of the set actually excised, and the order and girth of the graph
    actually assembled.  A wrong excision or a wrong girth breaks these.
    """
    r, rem = divmod(src_girth, 4)
    eps = 2 ** (r + 1) - 2
    ck("biggs_epsilon_equals_the_size_of_the_excised_set",
       rem in (0, 1) and eps == len(set(excised)),
       "source girth %d = 4*%d + %d, so epsilon = 2^(r+1) - 2 = %d, and the "
       "excised set has %d vertices" % (src_girth, r, rem, eps,
                                        len(set(excised))))
    ck("biggs_order_and_girth_drop_as_stated",
       src_order - eps == out_order and out_girth == src_girth - 1,
       "%d - %d = %d vertices and the assembled graph has %d; girth %d -> %d"
       % (src_order, eps, src_order - eps, out_order, src_girth, out_girth))


def check_S_is_biggs_tree(adj152):
    """S must be an adjacent pair together with everything at distance <= 2."""
    found = []
    for a in range(len(adj152)):
        for b in adj152[a]:
            if a >= b:
                continue
            ball = set([a, b])
            for u in (a, b):
                for w in adj152[u]:
                    ball.add(w)
                    ball.update(adj152[w])
            if ball == set(S_EXCISED):
                found.append((a, b))
    ck("S_is_the_closed_2_ball_of_an_adjacent_pair", len(found) == 1,
       "exactly one adjacent pair has closed 2-ball equal to S: %s; "
       "size 2 + 4 + 8 = 14 as girth 12 forces" % (found,))


def is_3_11_graph(adj, order):
    """Membership in the order spectrum needs all four properties at once:
    simple, connected, cubic, girth exactly 11 -- not the girth alone."""
    return (len(adj) == order
            and not any(v in adj[v] for v in range(len(adj)))
            and all(v in adj[w] for v in range(len(adj)) for w in adj[v])
            and degree_multiset(adj) == [3] * order
            and is_connected(adj)
            and girth(adj) == 11)


def check_spectrum_bound(constructed):
    """N(3,11) <= 138 from: >= 144 known, 140 known, and the two new orders."""
    limit = 400
    # inputs taken from the literature the paper cites, not re-derived here:
    known = set(n for n in range(144, limit + 1, 2))      # every even n >= 144
    known.add(140)                                       # order 140
    known |= constructed                                  # verified above
    target = set(n for n in range(138, limit + 1, 2))
    gap = sorted(target - known)
    ck("every_even_order_from_138_is_covered", not gap,
       "all %d even orders in [138, %d] are accounted for" % (len(target), limit)
       if not gap else "even orders in [138, %d] not accounted for: %s"
       % (limit, gap[:5]))
    least = None                                          # derive N, do not assume it
    for n in range(2, limit + 1, 2):
        if all(m in known for m in range(n, limit + 1, 2)):
            least = n
            break
    ck("derived_N_3_11_upper_bound_is_138", least == 138,
       "the least even N with every even order in [N, %d] covered is %s; "
       "paper claims N(3,11) <= 138" % (limit, least))
    unresolved = set(range(128, 143, 2))
    ck("new_orders_lay_in_the_unresolved_range",
       constructed == set([138, 142]) and constructed <= unresolved,
       "the two constructed orders %s were among the even orders 128..142 "
       "left open" % (sorted(constructed),))


